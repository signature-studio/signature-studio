#!/usr/bin/env python3
"""pick1 (decision 0242): ops-pick1.tsv -> G3 scripts (same shape as lift/harness/parity/mk-scripts.py: prelude = wizard closed, Basic.flp opened; `cpu LABEL` before every snapshot in the native script).
usage: mk-pick1-scripts.py OUTDIR      -> OUTDIR/pk.native.g3, OUTDIR/pk.wasm.g3.  THE INPUT IS A HARNESS SIMULATION, NOT A USER OPERATION."""
import sys, os
out = sys.argv[1]; os.makedirs(out, exist_ok=True)
BASIC = r'C:\Program Files\Image-Line\FL Studio 21\Data\Templates\Minimal\Basic\Basic.flp'
def expand(c):
    if not c.startswith('@'): return [c]
    t = c.split(); k = t[0]
    if k == '@drag':
        b = t[1]; x0, y0, x1, y1, n, dt = [int(v) for v in t[2:8]]
        r = ['move %d %d' % (x0, y0), 'down ' + b, 'advance %d' % dt]
        for i in range(1, n + 1): r += ['move %d %d' % (x0 + (x1 - x0) * i // n, y0 + (y1 - y0) * i // n), 'advance %d' % dt]
        return r + ['up ' + b, 'advance 300']
    if k == '@wheel':
        x, y, d, n, dt = [int(v) for v in t[1:6]]; r = []
        for i in range(n): r += ['wheel %d %d %d' % (x, y, d), 'advance %d' % dt]
        return r
    if k == '@moves':
        x0, y0, x1, y1, n, dt = [int(v) for v in t[1:7]]; r = ['move %d %d' % (x0, y0), 'advance %d' % dt]
        for i in range(1, n + 1): r += ['move %d %d' % (x0 + (x1 - x0) * i // n, y0 + (y1 - y0) * i // n), 'advance %d' % dt]
        return r
    raise SystemExit('unknown macro ' + c)
here = os.path.dirname(os.path.abspath(__file__)); ops = []
for ln in open(os.path.join(here, 'ops-pick1.tsv'), encoding='utf-8'):
    if ln.startswith('#') or not ln.strip(): continue
    f = ln.rstrip('\n').split('\t'); ops.append(f[:6])
for flavour in ('native', 'wasm'):
    L = []
    def snap(name):
        if flavour == 'native': L.append('cpu ' + name)
        L.append('snap ' + name)
    L.append('# pick1 (decision 0242) session pk (%s): generated by tools/mk-pick1-scripts.py from ops-pick1.tsv; THE INPUT IS A HARNESS SIMULATION, NOT A USER OPERATION' % flavour)
    snap('wiz0'); L += ['advance 3000', 'tap 13', 'advance 3000']; snap('e03')
    L += ['open ' + BASIC, 'advance 1500']; snap('opened')
    for s, op, cat, desc, cmds, kind in ops:
        for c in cmds.split(' ; '): L += expand(c.strip())
        snap(op)
    if flavour == 'native': L.append('cpu end')
    L.append('end')
    open(os.path.join(out, 'pk.%s.g3' % flavour), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('ops', len(ops))
