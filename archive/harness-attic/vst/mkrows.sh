#!/bin/bash
# Writes the rows file for mk_common.py --extra-rows from vst_hm.def. usage: mkrows.sh OUT_rows.txt
HERE=$(cd "$(dirname "$0")" && pwd)
k=0
{
    echo "# generated by mkrows.sh from vst_hm.def (decision 0156): host-object methods of the VST3 harness"
    for n in $(sed -n 's/^HM(\([A-Za-z0-9_]*\)).*/\1/p' "$HERE/vst_hm.def"); do
        printf '0x%x vst_hm_%s\n' $((0x7FFC00000000 + 0x10 * (k + 1))) "$n"
        k=$((k + 1))
    done
} > "$1"
