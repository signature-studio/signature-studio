#!/usr/bin/env python3
"""perf2 (decision 0138): writes the API-counter wrappers of a build without the entry hook (lift/harness/web/perf2/perf2_probe.c).

usage: gen_p2_wraps.py SYMBOLS.txt OUT_DIR
  SYMBOLS.txt  one `fle_imp_<API>` symbol per line (the global functions that the runtime objects define: `nm -g --defined-only` for native, llvm-nm for wasm objects)
  OUT_DIR      gets p2_wraps.c (one __wrap_fle_imp_<API> per symbol: it increments p2_cnt[index] and calls the real stub; the guest registers R[] are not touched; the wrapper of timeGetTime then calls p2_frame_hook())
               and p2_wrap_flags.txt (the `-Wl,--wrap=fle_imp_<API>` flags for the link)
An existing output file is refused. Same shape as lift/harness/idle/gen_idle_wraps.py (decision 0129), which needs the entry hook; this one does not."""
import os
import re
import sys

PREFIX = "fle_imp_"


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 64
    syms = sorted({s.strip() for s in open(argv[1], encoding="utf-8") if s.strip()})
    for s in syms:
        if not s.startswith(PREFIX) or not re.fullmatch(r"[A-Za-z0-9_]+", s):
            print("gen_p2_wraps: not a fle_imp_ symbol: %r" % s)
            return 2
    if not syms:
        print("gen_p2_wraps: no symbol")
        return 2
    out = argv[2]
    cpath = os.path.join(out, "p2_wraps.c")
    fpath = os.path.join(out, "p2_wrap_flags.txt")
    for p in (cpath, fpath):
        if os.path.exists(p):
            print("gen_p2_wraps: %s exists (never overwritten)" % p)
            return 2
    lines = ["/* generated by lift/harness/web/perf2/gen_p2_wraps.py: do not edit. %d wrappers of the stubs of the runtime (decision 0138). */" % len(syms),
             "void p2_frame_hook(void);", "unsigned long long p2_cnt[%d];" % len(syms), ""]
    for i, s in enumerate(syms):
        lines.append("void __real_%s(void);" % s)
        if s == PREFIX + "timeGetTime":
            lines.append("void __wrap_%s(void) { p2_cnt[%du]++; __real_%s(); p2_frame_hook(); }" % (s, i, s))
        else:
            lines.append("void __wrap_%s(void) { p2_cnt[%du]++; __real_%s(); }" % (s, i, s))
    lines.append("")
    lines.append("const char *const p2_wrap_names[] = {")
    for s in syms:
        lines.append('    "%s",' % s[len(PREFIX):])
    lines.append("};")
    lines.append("const unsigned p2_wrap_count = %d;" % len(syms))
    with open(cpath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(fpath, "w", encoding="utf-8") as f:
        f.write(" ".join("-Wl,--wrap=%s" % s for s in syms) + " -Wl,--wrap=fle_stop\n")
    print("gen_p2_wraps: %d wrappers -> %s, %s" % (len(syms), cpath, fpath))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
