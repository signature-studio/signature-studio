#ifndef __EMSCRIPTEN__
/* FLE_PERF2_PROFILE_FILE=<file> [FLE_PERF2_PROFILE_FROM=<s>] (native only): a SIGPROF sampler (200 Hz of CPU time) that starts FROM seconds (default 0) after the probe started, stores the interrupted RIP, and appends the PCs to <file> at every sample
 * (file format v2: the first u64 = the run-time address of p2_frame_hook_addr_anchor, then records [k, rip, k return addresses of the C stack];  so that a PC can be turned into a nm address of the same binary: pc - base + nm_address_of_p2_frame_hook). tools/profsum.py of docs/investigations/perf2 reads it. Information only. */
#define PROF_DEPTH 40
static uint64_t *pcs;
static size_t npc, cap_pc = 1u << 22;
static FILE *pf;
static int prof_on;
static void prof_handler(int sig, siginfo_t *si, void *uc_) {
    ucontext_t *uc = (ucontext_t *)uc_;
    void *bt[PROF_DEPTH + 3];
    int n, i, k = 0;
    (void)sig; (void)si;
    if (npc + PROF_DEPTH + 3 >= cap_pc) return;
    n = backtrace(bt, PROF_DEPTH + 3);
    /* bt[0] = this handler, bt[1] = the signal trampoline, bt[2..] = the interrupted PC and its callers (FLE_PERF2_PROFILE_STACK=1: the C stack is stored after the RIP; the lifted functions are C functions that call each other) */
    pcs[npc++] = (uint64_t)n > 2 ? (uint64_t)(n - 2) : 0;
    pcs[npc++] = (uint64_t)uc->uc_mcontext.gregs[REG_RIP];
    for (i = 2; i < n && k < PROF_DEPTH; i++, k++) pcs[npc++] = (uint64_t)(uintptr_t)bt[i];
    pcs[npc - k - 2] = (uint64_t)k;
}
static void prof_start(void) {
    struct sigaction sa;
    struct itimerval it;
    uint64_t base = (uint64_t)(uintptr_t)&p2_frame_hook_addr_anchor;
    if (prof_on || !getenv("FLE_PERF2_PROFILE_FILE")) return;
    pcs = (uint64_t *)malloc(cap_pc * sizeof *pcs);
    pf = fopen(getenv("FLE_PERF2_PROFILE_FILE"), "wb");
    if (!pcs || !pf) return;
    fwrite(&base, 8, 1, pf);
    { void *warm[4]; backtrace(warm, 4); }   /* load the unwinder before the first signal */
    memset(&sa, 0, sizeof sa);
    sa.sa_sigaction = prof_handler;
    sa.sa_flags = SA_SIGINFO | SA_RESTART;
    sigaction(SIGPROF, &sa, NULL);
    it.it_interval.tv_sec = 0; it.it_interval.tv_usec = 5000;
    it.it_value = it.it_interval;
    setitimer(ITIMER_PROF, &it, NULL);
    prof_on = 1;
}
static void prof_flush(void) {
    if (!prof_on) return;
    fwrite(pcs, 8, npc, pf);
    npc = 0;
    fflush(pf);
}
#endif

static unsigned long long rss_or_memory(void) {
#ifdef __EMSCRIPTEN__
    return (unsigned long long)__builtin_wasm_memory_size(0) * 65536ull;
#else
    FILE *f = fopen("/proc/self/statm", "r");
    unsigned long long a = 0, b = 0;
    if (f) { if (fscanf(f, "%llu %llu", &a, &b) != 2) b = 0; fclose(f); }
    return b * (unsigned long long)sysconf(_SC_PAGESIZE);
#endif
}

static int cmp_d(const void *a, const void *b) { double x = *(const double *)a, y = *(const double *)b; return x < y ? -1 : x > y; }
static void dt_stats(char *out, size_t cap) {
    if (!n_dts) { snprintf(out, cap, "n=0"); return; }
    double sum = 0;
    for (unsigned i = 0; i < n_dts; i++) sum += dts[i];
    qsort(dts, n_dts, sizeof dts[0], cmp_d);
    snprintf(out, cap, "n=%u mean_ms=%.2f p50=%.2f p90=%.2f p99=%.2f max=%.2f", n_dts, 1000.0 * sum / n_dts, 1000.0 * dts[n_dts / 2], 1000.0 * dts[(unsigned)(n_dts * 0.9)], 1000.0 * dts[(unsigned)(n_dts * 0.99)], 1000.0 * dts[n_dts - 1]);
    n_dts = 0;
}

static void top_apis(char *out, size_t cap) {
    unsigned idx[8] = {0};
    unsigned long long d[8] = {0};
    unsigned k, j, n = p2_wrap_count < 8192 ? p2_wrap_count : 8192;
    size_t o = 0;
    for (k = 0; k < n; k++) {
        unsigned long long dv = p2_cnt[k] - prev_cnt[k];
        if (!dv) continue;
        for (j = 0; j < 8; j++)
            if (dv > d[j]) { memmove(d + j + 1, d + j, (7 - j) * sizeof d[0]); memmove(idx + j + 1, idx + j, (7 - j) * sizeof idx[0]); d[j] = dv; idx[j] = k; break; }
    }
    out[0] = 0;
    for (j = 0; j < 8 && d[j]; j++) o += (size_t)snprintf(out + o, cap - o, "%s%s=%llu", j ? "," : "", p2_wrap_names[idx[j]], d[j]);
    for (k = 0; k < n; k++) prev_cnt[k] = p2_cnt[k];
}

static void window_hash(unsigned *lines, char hex[65]) {
    char *buf = NULL;
    size_t sz = 0;
    FILE *f = open_memstream(&buf, &sz);
    sha_t s;
    unsigned n = 0;
    size_t i;
    hex[0] = 0;
    *lines = 0;
    if (!f) return;
    fle_win_table_report(f);
    fclose(f);
    if (!buf) return;
    for (i = 0; i < sz; i++) if (buf[i] == '\n') n++;
    sha_init(&s);
    sha_update(&s, (const uint8_t *)buf, sz);
    sha_final(&s, hex);
    *lines = n;
    free(buf);
}

static void dump_surface(unsigned lid, const fle_rsurf *v) {
    const char *dir = getenv("FLE_PERF2_DUMP_DIR");
    unsigned long long de = envnum("FLE_PERF2_DUMP_EVERY", 12);
    if (dir && *dir && de && (sample_no == 1 || sample_no % de == 0)) {
        char path[512];
        FILE *f;
        mkdir(dir, 0755);
        snprintf(path, sizeof path, "%s/lid%u-%04u-%ux%u.bgrx", dir, lid, sample_no, (unsigned)v->width, (unsigned)v->height);
        f = fopen(path, "wb");
        if (f) {
            for (uint32_t y = 0; y < v->height; y++) fwrite(v->bits + (uint64_t)y * v->stride, 4, v->width, f);
            fclose(f);
            printf(" dump=%s", path);
        }
    }
}

static void surface_line(unsigned lid, const fle_rsurf *v, unsigned js_every, int is_stop) {
    char hex[65];
    uint64_t nz = 0;
    rgba_sha(v->bits, v->width, v->height, v->stride, hex, &nz);
    printf("p2: surface #%u%s lid=%u size=%ux%u nonzero=%" PRIu64 " rgba_sha256=%s", sample_no, is_stop ? " STOP" : "", lid, (unsigned)v->width, (unsigned)v->height, nz, hex);
    if (lid == 13 && v->width && v->height && v->width <= 8192 && v->height <= 8192) {
        size_t words = (size_t)v->width * v->height;
        uint32_t *cur = (uint32_t *)malloc(words * 4u);
        if (cur) {
            for (uint32_t y = 0; y < v->height; y++) memcpy(cur + (size_t)y * v->width, v->bits + (uint64_t)y * v->stride, (size_t)v->width * 4u);
            if (prev13 && prev13_w == v->width && prev13_h == v->height) {
                unsigned grid[8][8];
                uint64_t chg = 0;
                uint32_t x0 = v->width, y0 = v->height, x1 = 0, y1 = 0;
                memset(grid, 0, sizeof grid);
                for (uint32_t y = 0; y < v->height; y++) {
                    const uint32_t *a = cur + (size_t)y * v->width, *b = prev13 + (size_t)y * v->width;
                    for (uint32_t x = 0; x < v->width; x++)
                        if (((a[x] ^ b[x]) & 0x00ffffffu) != 0) {
                            chg++;
                            if (x < x0) x0 = x;
                            if (x >= x1) x1 = x + 1;
                            if (y < y0) y0 = y;
                            if (y >= y1) y1 = y + 1;
                            grid[y * 8 / v->height][x * 8 / v->width]++;
                        }
                }
                printf(" changed=%" PRIu64, chg);
                if (chg) {
                    printf(" bbox=%u,%u,%u,%u grid=", x0, y0, x1, y1);
                    for (int gy = 0; gy < 8; gy++) for (int gx = 0; gx < 8; gx++) printf("%s%u", (gy || gx) ? "," : "", grid[gy][gx]);
                }
            }
            free(prev13);
            prev13 = cur; prev13_w = v->width; prev13_h = v->height; prev13_words = words;
        }
    }
    dump_surface(lid, v);
#ifdef __EMSCRIPTEN__
    if (js_every && (sample_no == 1 || is_stop || sample_no % js_every == 0)) p2_js_surface_event(3, lid, (unsigned)(uintptr_t)v->bits, v->width, v->height, v->stride);
#else
    (void)js_every;
#endif
    printf("\n");
}

static void sample(double now, int is_stop) {
    unsigned long long tg = n_frames, dfr = n_frames - prev_frames;
    double wall = now - t0, dw = now - t_prev;
    double virt = (double)(fle_sys_clock_ticks() / FLE_TICKS_PER_MS) / 1000.0, dv = virt - v_prev;
    char top[640], whex[65], dtb[200], thb[400];
    unsigned wl = 0, lid;
    unsigned long long te = envnum("FLE_PERF2_THREADS_EVERY", 12), je = envnum("FLE_PERF2_JS_EVERY", 1);
    sample_no++;
    top_apis(top, sizeof top);
    dt_stats(dtb, sizeof dtb);
    {
        size_t o = 0;
        unsigned t;
        thb[0] = 0;
        for (t = 0; t < 32; t++)
            if (by_thread[t] != prev_by_thread[t]) { o += (size_t)snprintf(thb + o, sizeof thb - o, "%s%u:%llu", o ? "," : "", t, by_thread[t] - prev_by_thread[t]); prev_by_thread[t] = by_thread[t]; }
    }
    printf("p2: sample #%u wall=%.2f virtual=%.3f frames=%llu interval_wall=%.2f frames_in_interval=%llu fps_wall=%.3f fps_virtual=%.3f mem=%llu mono=%.3f%s\n", sample_no, wall, virt, tg, dw, dfr, dw > 0 ? (double)dfr / dw : 0.0,
           dv > 0 ? (double)dfr / dv : 0.0, rss_or_memory(), now, is_stop ? " STOP" : "");
    printf("p2: frames #%u by_thread=%s dt: %s\n", sample_no, thb, dtb);
    printf("p2: apis #%u %s\n", sample_no, top);
    window_hash(&wl, whex);
    printf("p2: windows #%u lines=%u sha256=%s\n", sample_no, wl, whex);
    for (lid = 0; lid < 128; lid++) {
        const fle_rsurf *v = fle_raster_surface_peek(lid);
        if (v && v->bits && v->bpp == 32 && v->width && v->height) surface_line(lid, v, (unsigned)je, is_stop);
    }
    if (fle_thread_report && te && (sample_no == 1 || sample_no % te == 0)) {
        printf("p2: threads #%u\n", sample_no);
        fle_thread_report(stdout);
    }
    fflush(stdout);
#ifdef __EMSCRIPTEN__
    p2_js_sample(wall, virt, (double)tg);
#else
    prof_flush();
#endif
    prev_frames = n_frames; t_prev = now; v_prev = virt;
}


/* FLE_PERF2_FRAME_DIFF=1 (information only): at every call of p2_frame_hook (= every timeGetTime of the guest) the surface of lid 13 is compared with its copy at the previous call; when pixels differ one line
 * "p2d: call=<n> frame=<n of the frame thread 2 or all> thr=<guest thread> virt=<s> changed=<pixels> rects=x0,y0,x1,y1:<pixels>;..." names the changed regions (32-pixel cells, 8-connected components, the 8 largest). FLE_PERF2_FRAME_DUMP=<dir> and
 * FLE_PERF2_FRAME_DUMP_MIN=<pixels> (default 50000) write the raw BGRX of lid 13 when at least that many pixels changed. */
static uint32_t *fd_prev;
static uint32_t fd_w, fd_h;
static unsigned fd_dumps;
static void frame_diff(void) {
    const fle_rsurf *v = fle_raster_surface_peek(13);
    enum { CS = 32 };
    if (!v || !v->bits || v->bpp != 32 || !v->width || !v->height || v->width > 4096 || v->height > 4096) return;
    {
        uint32_t w = v->width, h = v->height, cw = (w + CS - 1) / CS, ch = (h + CS - 1) / CS;
        uint32_t *cur = (uint32_t *)malloc((size_t)w * h * 4u);
        unsigned *cnt, *lab;
        uint64_t chg = 0;
        if (!cur) return;
        for (uint32_t y = 0; y < h; y++) memcpy(cur + (size_t)y * w, v->bits + (uint64_t)y * v->stride, (size_t)w * 4u);
        if (fd_prev && fd_w == w && fd_h == h) {
            cnt = (unsigned *)calloc((size_t)cw * ch, sizeof *cnt);
            lab = (unsigned *)calloc((size_t)cw * ch, sizeof *lab);
            if (cnt && lab) {
                for (uint32_t y = 0; y < h; y++) {
                    const uint32_t *a = cur + (size_t)y * w, *b = fd_prev + (size_t)y * w;
                    if (memcmp(a, b, (size_t)w * 4u) == 0) continue;
                    for (uint32_t x = 0; x < w; x++) if (((a[x] ^ b[x]) & 0x00ffffffu) != 0) { chg++; cnt[(y / CS) * cw + x / CS]++; }
                }
                if (chg) {
                    struct { uint32_t x0, y0, x1, y1; uint64_t n; } R[64];
                    unsigned nr = 0, c;
                    for (c = 0; c < cw * ch; c++) {
                        uint32_t stack_n = 0, *st;
                        if (!cnt[c] || lab[c] || nr >= 64) continue;
                        st = (uint32_t *)malloc((size_t)cw * ch * 4u);
                        if (!st) break;
                        R[nr].x0 = cw; R[nr].y0 = ch; R[nr].x1 = 0; R[nr].y1 = 0; R[nr].n = 0;
                        st[stack_n++] = c; lab[c] = 1;
                        while (stack_n) {
                            uint32_t k = st[--stack_n], kx = k % cw, ky = k / cw;
                            int dx, dy;
                            R[nr].n += cnt[k];
                            if (kx < R[nr].x0) R[nr].x0 = kx;
                            if (kx > R[nr].x1) R[nr].x1 = kx;
                            if (ky < R[nr].y0) R[nr].y0 = ky;
                            if (ky > R[nr].y1) R[nr].y1 = ky;
                            for (dy = -1; dy <= 1; dy++) for (dx = -1; dx <= 1; dx++) {
                                int64_t nx = (int64_t)kx + dx, ny = (int64_t)ky + dy;
                                if (nx < 0 || ny < 0 || nx >= (int64_t)cw || ny >= (int64_t)ch) continue;
                                if (cnt[ny * cw + nx] && !lab[ny * cw + nx]) { lab[ny * cw + nx] = 1; st[stack_n++] = (uint32_t)(ny * cw + nx); }
                            }
                        }
                        free(st);
                        nr++;
                    }
                    for (unsigned i = 0; i < nr; i++) for (unsigned j = i + 1; j < nr; j++) if (R[j].n > R[i].n) { __typeof__(R[0]) t = R[i]; R[i] = R[j]; R[j] = t; }
                    printf("p2d: call=%llu thr=%u virt=%.3f changed=%llu rects=", n_frames, fle_thread_current ? fle_thread_current() : 0u, (double)(fle_sys_clock_ticks() / FLE_TICKS_PER_MS) / 1000.0, (unsigned long long)chg);
                    for (unsigned i = 0; i < nr && i < 8; i++) {
                        uint32_t x1 = (R[i].x1 + 1) * CS, y1 = (R[i].y1 + 1) * CS;
                        printf("%s%u,%u,%u,%u:%llu", i ? ";" : "", R[i].x0 * CS, R[i].y0 * CS, x1 > w ? w : x1, y1 > h ? h : y1, (unsigned long long)R[i].n);
                    }
                    {
                        const char *dir = getenv("FLE_PERF2_FRAME_DUMP");
                        unsigned long long mn = envnum("FLE_PERF2_FRAME_DUMP_MIN", 50000);
                        if (dir && *dir && chg >= mn && fd_dumps < 60) {
                            char path[512];
                            FILE *f;
                            mkdir(dir, 0755);
                            snprintf(path, sizeof path, "%s/call%05llu-lid13-%ux%u.bgrx", dir, n_frames, w, h);
                            f = fopen(path, "wb");
                            if (f) { fwrite(cur, 4, (size_t)w * h, f); fclose(f); fd_dumps++; printf(" dump=%s", path); }
                        }
                    }
                    printf("\n");
                }
            }
            free(cnt); free(lab);
        }
        free(fd_prev);
        fd_prev = cur; fd_w = w; fd_h = h;
    }
}

