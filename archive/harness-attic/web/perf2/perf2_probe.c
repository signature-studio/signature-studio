void p2_frame_hook(void) {
    double now = mono();
    if (!inited) {
        const char *s = getenv("FLE_PERF2_SAMPLE_SECONDS");
        interval = s && *s ? atof(s) : 5.0;
        if (interval < 0.5) interval = 0.5;
        t0 = t_prev = now;
        v_prev = (double)(fle_sys_clock_ticks() / FLE_TICKS_PER_MS) / 1000.0;
        next_at = now + interval;
        inited = 1;
        printf("p2: probe started: sample every %.1f s wall, API wrappers %u, mono=%.3f\n", interval, p2_wrap_count, now);
        fflush(stdout);
    }
#ifndef __EMSCRIPTEN__
    if (!prof_on && (now - t0) >= (double)envnum("FLE_PERF2_PROFILE_FROM", 0)) prof_start();
#endif
    n_frames++;
    {
        unsigned t = fle_thread_current ? fle_thread_current() : 0;
        by_thread[t < 32 ? t : 31]++;
        if (last_hook_t > 0 && n_dts < 16384) dts[n_dts++] = now - last_hook_t;
        last_hook_t = now;
    }
    {
        static int fd_on = -1;
        if (fd_on < 0) fd_on = getenv("FLE_PERF2_FRAME_DIFF") ? 1 : 0;
        if (fd_on) frame_diff();
    }
    if (now >= next_at) {
        sample(now, 0);
        next_at = now + interval;
    }
}

/* every named stop of the runtime (an idle stop, a wall, a time-out is not one) goes through fle_stop: one last sample with the surfaces, then the real stop */
void __real_fle_stop(const char *api, const char *why) __attribute__((noreturn));
void __wrap_fle_stop(const char *api, const char *why) {
    char first[200];
    size_t i;
    snprintf(first, sizeof first, "%s", why ? why : "");
    for (i = 0; first[i] && first[i] != '\n'; i++) {}
    first[i] = 0;
    if (!inited) p2_frame_hook();
    printf("p2: fle_stop api=%s why=%s\n", api ? api : "?", first);
    sample(mono(), 1);
    __real_fle_stop(api, why);
}
