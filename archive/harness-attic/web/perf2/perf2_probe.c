/* FLE_PERF2_TRACE_WRITES=<min area in pixels> (native only; the link wraps fle_raster_wrote): every write of at least that many pixels into the surface of lid 13 is printed as "p2w: frame=<timeGetTime calls so far> thr=<guest thread> api=<GDI API> rect=x0,y0,x1,y1" (at most 20000 lines). Information only. */
void __real_fle_raster_wrote(const fle_rsurf *surf, fle_rrect r, const char *api);
void __wrap_fle_raster_wrote(const fle_rsurf *surf, fle_rrect r, const char *api) {
    static long long min_area = -2;
    static unsigned lines;
    __real_fle_raster_wrote(surf, r, api);
    if (min_area == -2) { const char *e = getenv("FLE_PERF2_TRACE_WRITES"); min_area = e && *e ? atoll(e) : -1; }
    if (min_area >= 0 && lines < 20000 && surf && surf == fle_raster_surface_peek(13)) {
        long long w = r.x1 - r.x0, h = r.y1 - r.y0;
        if (w > 0 && h > 0 && w * h >= min_area) {
            lines++;
            printf("p2w: frame=%llu thr=%u api=%s rect=%lld,%lld,%lld,%lld\n", n_frames, fle_thread_current ? fle_thread_current() : 0u, api ? api : "?", (long long)r.x0, (long long)r.y0, (long long)r.x1, (long long)r.y1);
        }
    }
}
