/* perf2 (decision 0138, PROVISIONAL): the observation of a build that has NO entry hook (-O2, no -finstrument-functions; native and wasm). Harness only: a new file, compiled and linked only by the perf2 scripts
 * (build_native_fast.sh). Nothing in lift/runtime or the other harness files is changed for it.
 *
 * A build without the entry hook cannot count lifted entries (trace_call_count() stays 0) and cannot see the idle detector's "no new function" condition. What this file gives instead, from the guest's own frame clock:
 *   - the link wraps every runtime API stub (-Wl,--wrap=fle_imp_<API>, the wrappers are generated by gen_p2_wraps.py from the runtime objects): a counter per API (the "API trace" of an optimised build; a wrapper only counts and calls the real stub);
 *   - the wrapper of timeGetTime (thread 2 of the engine reads it once per drawn frame, decision 0132) calls p2_frame_hook(): every FLE_PERF2_SAMPLE_SECONDS (default 5) wall seconds it prints ONE line "p2: sample ..." with
 *     the wall time, the virtual clock, the number of timeGetTime calls (= frames, an approximation: other threads may call it), the frame rate of the last interval in wall and in virtual time, the top API counts of the interval,
 *     the memory (RSS native / linear memory wasm), and for every live window surface (lid 0..127, 32-bit) its size, number of non-zero pixels and the SHA-256 of the surface as RGBA with A = 255 (what a canvas read-back gives);
 *     for the first surface of lid 13 also the number of pixels that differ from the previous sample, their bounding box and an 8 x 8 grid of changed-pixel counts;
 *   - the window table (fle_win_table_report) as a hash and a line count, the thread table (fle_thread_report) in full at the first sample and every FLE_PERF2_THREADS_EVERY (default 12) samples;
 *   - FLE_PERF2_DUMP_DIR=<dir> (native): the raw BGRX bytes of lid 13 at the first sample and every FLE_PERF2_DUMP_EVERY (default 12) samples; wasm: Module.fleSurfaceEvent(3, ...) every FLE_PERF2_JS_EVERY (default 1) samples, which the page's Worker draws
 *     on canvas A (it copies the pixels at that moment).
 * Sampling happens at a call of timeGetTime from the guest, i.e. at the start of a frame of thread 2; the other guest threads are cooperative (decision 0122) and yield only inside API calls, so a surface can be caught in the middle of a paint by thread 0 only if that
 * thread yielded inside its paint (not checked). The lines are information; no behaviour of the guest depends on them. */
