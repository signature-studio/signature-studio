// Regenerates tests/harness/shell-cases.tsv from shell-cases.src with opencode's OWN shell scanner (the part that splits a command into the pieces the
// permission rules see). Needs bun and the opencode source clone; the test run itself does not (it reads the .tsv). Run from the repository root:
//   bun run tests/harness/lib/gen-shell-cases.ts            (writes shell-cases.tsv)
//   bun run tests/harness/lib/gen-shell-cases.ts --check    (exit 1 when the .tsv differs from a fresh scan; tests/harness/t02 runs this when bun and the clone exist)
import { Effect } from "effect"
import { readFileSync, writeFileSync } from "node:fs"
import { ShellParse } from "/home/ubuntu/work/opencode/packages/core/src/shell/parse.ts"

const here = new URL(".", import.meta.url).pathname + "../"
const lines = readFileSync(here + "shell-cases.src", "utf8").split("\n").filter((l) => l.trim() !== "" && !l.startsWith("#"))
const out: string[] = []
for (const line of lines) {
  const [agent, expect, ...rest] = line.split("\t")
  const command = rest.join("\t")
  const r = await Effect.runPromise(Effect.result(ShellParse.scan(command, "/bin/bash", "/home/ubuntu/work/signature-studio")))
  if (r._tag === "Failure") throw new Error("scanner cannot analyze: " + command + " (" + String((r.failure as Error).message) + ")")
  out.push([agent, expect, JSON.stringify(r.success.commands.map((c: any) => c.resource)), command].join("\t"))
}
const text = "# agent<TAB>expect<TAB>resources(JSON, as split by opencode's scanner)<TAB>command. Generated by lib/gen-shell-cases.ts. Do not edit.\n" + out.join("\n") + "\n"
if (process.argv.includes("--check")) {
  const current = readFileSync(here + "shell-cases.tsv", "utf8")
  if (current !== text) { console.error("shell-cases.tsv is out of date: run bun run tests/harness/lib/gen-shell-cases.ts"); process.exit(1) }
  console.log("shell-cases.tsv matches a fresh scan (" + out.length + " cases)")
} else {
  writeFileSync(here + "shell-cases.tsv", text)
  console.log("wrote shell-cases.tsv (" + out.length + " cases)")
}
