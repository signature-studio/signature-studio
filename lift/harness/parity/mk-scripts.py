#!/usr/bin/env python3
"""parity1 (decision 0226): ops.tsv -> G3 scripts. usage: mk-scripts.py OUTDIR [--display WxH]
For every session S writes S.native.g3 (with a `cpu LABEL` line before every snapshot: native-only command of lift/harness/fruity_g3.c) and S.wasm.g3 (snapshots only; the `cpu` command does not exist on wasm).
The session `boot` starts from the first idle; every other session has the prelude: wizard closed, Basic.flp opened (the same commands as lift/out-ship2/scripts/flp-basic.g3).
THE INPUT IS A HARNESS SIMULATION, NOT A USER OPERATION."""
import sys, os
out = sys.argv[1]
disp = None
if '--display' in sys.argv:
    disp = sys.argv[sys.argv.index('--display') + 1].replace('x', ' ')
os.makedirs(out, exist_ok=True)
BASIC = r'C:\Program Files\Image-Line\FL Studio 21\Data\Templates\Minimal\Basic\Basic.flp'
def expand(c):
    # macros (continuous input at a fixed event period; 16 ms = 62.5 events/s):
    #   @drag BTN x0 y0 x1 y1 N DT   move to (x0,y0), press BTN (L|M|R), N moves along the line every DT virtual ms, release
    #   @wheel X Y DELTA N DT        N wheel events of DELTA at (X,Y) every DT virtual ms
    #   @moves x0 y0 x1 y1 N DT      N pointer moves without a button
    if not c.startswith('@'):
        return [c]
    t = c.split(); k = t[0]
    if k == '@drag':
        b = t[1]; x0, y0, x1, y1, n, dt = [int(v) for v in t[2:8]]
        r = ['move %d %d' % (x0, y0), 'down ' + b, 'advance %d' % dt]
        for i in range(1, n + 1):
            r += ['move %d %d' % (x0 + (x1 - x0) * i // n, y0 + (y1 - y0) * i // n), 'advance %d' % dt]
        return r + ['up ' + b, 'advance 300']
    if k == '@wheel':
        x, y, d, n, dt = [int(v) for v in t[1:6]]
        r = []
        for i in range(n):
            r += ['wheel %d %d %d' % (x, y, d), 'advance %d' % dt]
        return r
    if k == '@moves':
        x0, y0, x1, y1, n, dt = [int(v) for v in t[1:7]]
        r = ['move %d %d' % (x0, y0), 'advance %d' % dt]
        for i in range(1, n + 1):
            r += ['move %d %d' % (x0 + (x1 - x0) * i // n, y0 + (y1 - y0) * i // n), 'advance %d' % dt]
        return r
    raise SystemExit('unknown macro ' + c)
sessions = {}
order = []
here = os.path.dirname(os.path.abspath(__file__))
for ln in open(os.path.join(here, 'ops.tsv'), encoding='utf-8'):
    if ln.startswith('#') or not ln.strip():
        continue
    f = ln.rstrip('\n').split('\t')
    s, op, cat, desc, cmds, kind = f[:6]
    if s not in sessions:
        sessions[s] = []
        order.append(s)
    sessions[s].append((op, cat, desc, cmds, kind))
for s in order:
    for flavour in ('native', 'wasm'):
        L = []
        def snap(name):
            if flavour == 'native':
                L.append('cpu ' + name)
            L.append('snap ' + name)
        L.append('# parity1 session %s (%s): generated by lift/harness/parity/mk-scripts.py from ops.tsv; THE INPUT IS A HARNESS SIMULATION, NOT A USER OPERATION' % (s, flavour))
        snap('wiz0')
        if disp:
            L.append('display ' + disp)
            L.append('advance 1500')
            snap('display')
        if s != 'boot':
            L += ['advance 3000', 'tap 13', 'advance 3000']
            snap('e03')
            L += ['open ' + BASIC, 'advance 1500']
            snap('opened')
        for op, cat, desc, cmds, kind in sessions[s]:
            for c in cmds.split(' ; '):
                L += expand(c.strip())
            snap(op)
        if flavour == 'native':
            L.append('cpu end')
        L.append('end')
        open(os.path.join(out, '%s.%s.g3' % (s, flavour)), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('sessions', order, 'ops', sum(len(v) for v in sessions.values()))
