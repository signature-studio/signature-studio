#!/bin/bash
# Decision 0167, 0230, 0243: the generation stage of the shipped configuration without a native build and run: gen_two.sh rebase gen split merge over FLEngine and the seven modules, the realmod table (what b2d1's gen-final.sh did after it).
# usage (called by app/scripts/build-engine-bundle.sh stage_gen; every variable below is exported by it):
#   OUT=<ONAT> TAG=<tag> FEBIN LIFT FLE FLE_HOOKS FLE_SEEDS FLE_SEH_HANDLERS FLE_EXTRA_IMPORTS PRUNE_LIST H HL  bash gen-direct.sh
# The Blend2D module is lifted as decision 0160 (--seeds blend2d-4700000-seeds-wrapper.txt, no --pdata, --swap-entries blend2d-context-swap.txt), dsp_ippv2 with --hle-entries (decision 0162) and --prune-list (decision 0168),
# the sample decoder and the time-stretch engine as decision 0230 (--pdata and their seeds, the DLLs that ci/extract-dlls.tsv takes out of the installer: lift/out-sampledec/).
set -u -o pipefail
export PYTHONDONTWRITEBYTECODE=1
: "${OUT:?}" "${TAG:?}" "${FEBIN:?}" "${LIFT:?}" "${FLE:?}" "${H:?}" "${HL:?}"
: "${FLE_EXTRA_IMPORTS:?}" "${PRUNE_LIST:?}"
dsp_la="--seeds $H/seeds/dsp-ippv2-2000000-seeds-idle1.txt --hle-entries $H/hooks/dsp-hle-entries.txt --prune-list $PRUNE_LIST"
b2d_la="--seeds $H/b2d1/blend2d-4700000-seeds-wrapper.txt --site-overrides $H/hooks/blend2d-no-jit-sites.txt --swap-entries $H/b2d1/blend2d-context-swap.txt"
# the same fields as a4-multi.sh's mk_largs: pdata, seeds, hook-points, site-overrides (the order does not change the output); the dsp / blend2d lines above add --hle-entries / --swap-entries
specs=(
  "dsp_ippv2_x64.dll|$HL/out-ext/dsp_ippv2_x64.dll|0x2000000|$dsp_la"
  "blend2d.dll|$HL/out-blend2d/Blend2D.dll|0x4700000|$b2d_la"
  "quickfontcache_x64.dll|$HL/out-qfc/quickfontcache_x64.dll|0x1d00000|--pdata --hook-points $H/hooks/qfc-hook-points.txt"
  "freetype_x64.dll|$HL/out-wallQ/freetype/freetype_x64.dll|0x4b00000|--pdata --seeds $H/seeds/ft-seeds-4b00000-c2.txt"
  "iltools_x64.dll|$HL/out-inventory/extracted/ILTools_x64.dll|0x6000000|--pdata --seeds $H/seeds/iltools-6000000-seeds400.txt --hook-points $H/hooks/iltools-hook-points.txt"
  "oggio_x64.dll|$HL/out-sampledec/oggio_x64.dll|0xc000000|--pdata --seeds $H/seeds/dec1-seeds-oggio-c000000.txt"
  "elastique_x64.dll|$HL/out-sampledec/elastique_x64.dll|0xb000000|--pdata --seeds $H/seeds/elastique-seeds-all3.txt"
)
# FLE_EXTRA_IMPORTS (decision 0171) goes to every real module (the response table must be the same in all of them); FLEngine gets it from gen_two.sh itself
XARGS=" --extra-imports $FLE_EXTRA_IMPORTS"
MODULES=""; RMNAMES=""; k=0
for s in "${specs[@]}"; do
  IFS='|' read -r nm f b la <<< "$s"
  [ -r "$f" ] || { echo "gen-direct: cannot read $f" >&2; exit 2; }
  k=$((k + 1))
  MODULES="${MODULES:+$MODULES;}m$k|$f|$b|$la$XARGS||800"
  RMNAMES="${RMNAMES:+$RMNAMES;}m$k=$nm"
done
mkdir -p "$OUT/log"
export OUT TAG FEBIN LIFT FLE MODULES DLLDIR="v-$TAG/dll" FLE_PER_PART=3700 REAL_PER_PART=800 EXPECT_FLE_SHA=skip FRUITY_ROWS="$H/fruity-rows.txt"
export FLE_SEEDS="${FLE_SEEDS:-}" FLE_HOOKS="${FLE_HOOKS:-}" FLE_SEH_HANDLERS="${FLE_SEH_HANDLERS:-}"
bash "$H/two/gen_two.sh" rebase gen split merge > "$OUT/log/gen.out" 2> "$OUT/log/gen.err"
rc=$?
tail -5 "$OUT/log/gen.out"
[ $rc -eq 0 ] || { echo "gen-direct: gen_two.sh failed (exit $rc), see $OUT/log/gen.err" >&2; exit $rc; }
V=$OUT/v-$TAG; mkdir -p "$V/native"
awk -F'|' -v rm="$RMNAMES" 'BEGIN {
  print "/* generated by lift/harness/b2d2/gen-direct.sh from modules.txt as lift/harness/two/build_two_native.sh does */";
  print "#include \"fle_realmod.h\"";
  print "const fle_realmod_entry fle_realmod_table[] = {";
  np = split(rm, pairs, ";"); for (i = 1; i <= np; i++) { split(pairs[i], kv, "="); nm[kv[1]] = kv[2] }
}
$1 != "" { printf "    { \"%s\", UINT64_C(%s) },\n", nm[$1], $3; n++ }
END { print "};"; print "const uint64_t fle_realmod_count = " n ";" }' "$V/modules.txt" > "$V/native/realmod_table_gen.c"
sha256sum "$OUT/gen/flengine.c" "$V"/gen/m*.c "$V/src/common.c" | tee "$OUT/log/generated-c-sha256.txt"
