#!/bin/bash
# N-module native build (a measurement copy of lift/harness/two/build_two_native.sh; lift/out-three/harness-two).
# The units made by gen_two.sh (FLEngine + the rebased real modules, shared R/FL/X, one merged dispatch table) + the runtime (all
# fle_*.c, including fle_realmod.c) + a realmod_table.c that lists every real module + the harness main_two.c.
# Flags are those of lift/harness/wasm/build_native.sh. The native trace is harness/wasm/trace_native.c (tracked; the *.c.new files
# beside it belong to someone else and are not used).
#
# Differences from the one-module script:
#   - the modules come from $V/modules.txt (written by gen_two.sh; same "label|file|base|..." entries); the units of module L are
#     $V/src/L-NN.c and are compiled to $V/native/obj/L-NN.o; realmod_table.c is generated into $V/native/realmod_table_gen.c from
#     the list (name = lower-case basename of the file as the guest's LoadLibraryW spells it after normalisation, base = the
#     entry's base) and compiled to $V/native/obj-h/realmod_table.o, so that the table is per TAG, not shared;
#   - LIFT=<tree with runtime/ and harness/> (default: the lift/ above this script; set it to the `git archive` tree);
#   - RMNAMES="label=name;label=name" gives the table name of a module when it is not the lower-case file basename
#     (default for the label "dll": dsp_ippv2_x64.dll, as the one-module script).
#
# CENSUS COPY (decision 0097): lift/harness/census/ holds this script, gen_two.sh, merge_tables_n.py, two-native-run.sh and main_two.c as copies
# of lift/out-rdefs/three/harness-two/ (gen_two.sh, merge_tables_n.py and two-native-run.sh byte for byte). Changes here: main_two.c is the census
# version (census_begin/census_end around the entry call, no effect without FLE_CENSUS), harness/census/census.c is compiled and linked.
#
# usage: bash lift/harness/census/build_two_native.sh
# env:   OUT (the OUT of gen_two.sh)   TAG (the TAG of gen_two.sh)   JOBS=6   NATIVE_TRACE=<trace c file>
# Output: $OUT/v-$TAG/native/two-native. The FLEngine objects ($OUT/native/fle), the runtime objects ($OUT/native/rt) and the
# harness objects ($OUT/native/h) are shared by every TAG; a TAG has its own objects of the real modules and of common.c.
# Nothing is deleted or overwritten: a built object is skipped (move it away to rebuild it, e.g. the runtime objects after a
# runtime edit: the script does not detect a stale object).
set -u -o pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
LIFT=${LIFT:-$(cd "$HERE/../.." && pwd)}
OUT=${OUT:?OUT is not set}
TAG=${TAG:-red}
V="$OUT/v-$TAG"
RT="$LIFT/runtime"
JOBS=${JOBS:-6}
TR=${NATIVE_TRACE:-$LIFT/harness/wasm/trace_native.c}
RMNAMES=${RMNAMES:-}
[ -r "$V/modules.txt" ] || { echo "build: $V/modules.txt is missing (run gen_two.sh gen first)"; exit 2; }
mkdir -p "$OUT/tmp" "$OUT/native/fle" "$OUT/native/rt" "$OUT/native/h" "$V/native/obj" "$V/native/obj-h"
export TMPDIR="$OUT/tmp"
GEN="-std=gnu11 -O0 -g -w -fno-builtin-fprintf -fno-builtin-fputs -ffp-contract=off -fPIE -I$RT -finstrument-functions"

# the realmod table of this TAG, from modules.txt
RT_C="$V/native/realmod_table_gen.c"
if [ ! -e "$RT_C" ]; then
    {
        echo '/* generated by lift/out-three/harness-two/build_two_native.sh from modules.txt: the link-time registration of the real modules'
        echo ' * (lift/runtime/fle_realmod.h). Name = the spelling that normalize() of fle_load.c produces; base = the base the file was rebased to. */'
        echo '#include "fle_realmod.h"'
        echo 'const fle_realmod_entry fle_realmod_table[] = {'
        n=0
        while IFS='|' read -r label file base largs sha per; do
            [ -n "$label" ] || continue
            name=""
            IFS=';' read -ra pairs <<< "$RMNAMES"
            for p in "${pairs[@]:-}"; do [ "${p%%=*}" = "$label" ] && name="${p#*=}"; done
            if [ -z "$name" ]; then
                if [ "$label" = dll ]; then name=dsp_ippv2_x64.dll; else name=$(basename "$file" | tr 'A-Z' 'a-z'); fi
            fi
            printf '    { "%s", UINT64_C(%s) },\n' "$name" "$base"
            n=$((n + 1))
        done < "$V/modules.txt"
        echo '};'
        echo "const uint64_t fle_realmod_count = $n;"
    } > "$RT_C"
fi

cd "$OUT/native"
ls "$OUT"/src/fle-[0-9][0-9].c | xargs -P "$JOBS" -I{} bash -c 'b=$(basename {} .c); [ -e fle/$b.o ] || clang '"$GEN"' -c {} -o fle/$b.o' || exit 1
for f in "$RT"/fle_*.c; do b=$(basename "$f" .c); [ -e rt/$b.o ] || clang -std=gnu11 -O0 -g -Wall -Wextra -fPIE -I"$RT" -c "$f" -o rt/$b.o || exit 1; done
for f in image a4; do [ -e h/$f.o ] || clang -std=gnu11 -O1 -Wall -Wextra -fPIE -I"$RT" -I"$LIFT/harness" -c "$LIFT/harness/$f.c" -o h/$f.o || exit 1; done
[ -e h/census.o ] || clang -std=gnu11 -O1 -Wall -Wextra -fPIE -I"$RT" -I"$LIFT/harness" -I"$HERE" -c "$HERE/census.c" -o h/census.o || exit 1
[ -e h/main_two.o ] || clang -std=gnu11 -O1 -Wall -Wextra -fPIE -I"$RT" -I"$LIFT/harness" -I"$HERE" -c "$HERE/main_two.c" -o h/main_two.o || exit 1
[ -e h/trace.o ] || clang -std=gnu11 -O1 -Wall -Wextra -fPIE -I"$RT" -I"$LIFT/harness" -c "$TR" -o h/trace.o || exit 1
cd "$V/native"
[ -e obj-h/realmod_table.o ] || clang -std=gnu11 -O1 -Wall -Wextra -fPIE -I"$RT" -c "$RT_C" -o obj-h/realmod_table.o || exit 1
[ -e obj/common.o ] || clang $GEN -c "$V/src/common.c" -o obj/common.o || exit 1
# the units of every module: any file $V/src/<label>-NN.c (NN two digits); common.c and the *-tables.txt files do not match
ls "$V"/src/*-[0-9][0-9].c | xargs -P "$JOBS" -I{} bash -c 'b=$(basename {} .c); [ -e obj/$b.o ] || clang '"$GEN"' -c {} -o obj/$b.o' || exit 1
[ -e two-native ] && { echo "exists: $V/native/two-native (move it away to relink)"; exit 0; }
clang -pie -o two-native "$OUT"/native/h/main_two.o "$OUT"/native/h/image.o "$OUT"/native/h/a4.o "$OUT"/native/h/census.o "$OUT"/native/h/trace.o \
    obj-h/realmod_table.o obj/*.o "$OUT"/native/fle/*.o "$OUT"/native/rt/*.o -Wl,--wrap=fprintf -Wl,--wrap=fputs -lm \
    && echo "built $V/native/two-native"
