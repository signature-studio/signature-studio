"""Decision 0165 (vst3a): writes the extra-import rows and the stopping stubs for the imports of a PE that have no row in the import table (nor in the vst harness rows).
Every such import gets a row `<dll> <API> fle_imp_<API>` for fe-lift --extra-imports and a WEAK C function fle_imp_<API> that stops by name ("vst3a: ... called").
An answer is added by defining a strong fle_imp_<API> in vst3a_imp.c: the generated C does not change (the row exists from the start), only the link does.
usage: mk_stubs.py FILE imports_table.rs imports-vst.txt OUT_rows.txt OUT_stubs.c OUT_ordrows.txt      (ordinal imports get rows named dll!#N)"""
import re, sys, pefile
pe_path, tab, vstrows, out_rows, out_c, out_ord = sys.argv[1:7]
rows = set()
for l in open(tab):
    m = re.match(r'\s*\("([^"]+)",\s*"([^"]+)",\s*"fle_imp_', l)
    if m: rows.add((m.group(1).lower(), m.group(2)))
for l in open(vstrows):
    t = l.split('#', 1)[0].split()
    if len(t) >= 2: rows.add((t[0].lower(), t[1]))
pe = pefile.PE(pe_path, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_IMPORT']])
miss = []
ords = []
ordl = []
seen = set()
for e in pe.DIRECTORY_ENTRY_IMPORT:
    d = e.dll.decode().lower()
    for imp in e.imports:
        if imp.import_by_ordinal:
            # an ordinal import is named dll!#N by fe-decode (indirect.rs); pefile knows the names of ws2_32 ordinals, which are used for the C function only
            ords.append('%s!#%d' % (d, imp.ordinal))
            ordl.append((d, imp.ordinal, 'fle_imp_ord_%s_%d%s' % (d.replace('.dll', ''), imp.ordinal, ('_' + imp.name.decode()) if imp.name else ''), imp.address))
            continue
        n = imp.name.decode()
        if (d, n) in rows or (d, n) in seen: continue
        seen.add((d, n)); miss.append((d, n, 'fle_imp_' + n))
with open(out_rows, 'w') as f:
    f.write('# generated by mk_stubs.py (decision 0165): imports of %s without a row in the table; each is a stopping stub until vst3a_imp.c defines the answer\n' % pe_path.split('/')[-1])
    for d, n, c in miss: f.write('%s %s %s\n' % (d, n, c))
with open(out_c, 'w') as f:
    f.write('/* generated by mk_stubs.py (decision 0165): weak stopping stubs. A strong definition in vst3a_imp.c replaces one. */\n#include "vst3a.h"\n\n')
    for d, n, c in miss:
        f.write('__attribute__((weak)) void %s(void) { vst3a_unanswered("%s", "%s"); }\n' % (c, d, n))
    for d, o, c, a in ordl:
        f.write('__attribute__((weak)) void %s(void) { vst3a_unanswered("%s", "#%d"); }\n' % (c, d, o))
    f.write('\nconst vst3a_ord_entry vst3a_ord_table[] = {\n')
    for k, (d, o, c, a) in enumerate(ordl):
        f.write('    { "%s", %d, UINT64_C(%#x), %s },\n' % (d, o, 0x7FFC10000000 + 0x10 * (k + 1), c))
    f.write('};\nconst unsigned vst3a_ord_count = %d;\n' % len(ordl))
with open(out_ord, 'w') as f:
    f.write('# generated by mk_stubs.py: pseudo-VAs of the ordinal imports (extra rows of the dispatch table)\n')
    for k, (d, o, c, a) in enumerate(ordl): f.write('%#x %s\n' % (0x7FFC10000000 + 0x10 * (k + 1), c))
with open(out_ord + '.slots', 'w') as f:
    for k, (d, o, c, a) in enumerate(ordl): f.write('%#x %s %s\n' % (a, c, d))
print('rows', len(miss), 'ordinal imports', len(ords), ' '.join(ords))
