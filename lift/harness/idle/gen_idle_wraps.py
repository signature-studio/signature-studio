#!/usr/bin/env python3
"""Writes the API counters of the idle-continuation build (decision 0129; lift/harness/fruity.c, FLE_FRUITY_STABLE_SECONDS).

usage: gen_idle_wraps.py SYMBOLS.txt OUT_DIR
  SYMBOLS.txt  one `fle_imp_<API>` symbol per line (the global functions that the runtime objects define; build_two_native.sh takes them from `nm -g --defined-only`)
  OUT_DIR      gets idle_wraps.c (one __wrap_fle_imp_<API> per symbol that calls idle_api_note(index) and then the real function; the guest registers R[] are not touched)
               and idle_wrap_flags.txt (the `-Wl,--wrap=fle_imp_<API>` flags for the link)
Nothing outside OUT_DIR is touched; an existing file is refused. The wrapper never changes what the stub does."""
import os
import re
import sys

PREFIX = "fle_imp_"


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 64
    syms = sorted({s.strip() for s in open(argv[1], encoding="utf-8") if s.strip()})
    for s in syms:
        if not s.startswith(PREFIX) or not re.fullmatch(r"[A-Za-z0-9_]+", s):
            print("gen_idle_wraps: not a fle_imp_ symbol: %r" % s)
            return 2
    if not syms:
        print("gen_idle_wraps: no symbol")
        return 2
    out = argv[2]
    cpath = os.path.join(out, "idle_wraps.c")
    fpath = os.path.join(out, "idle_wrap_flags.txt")
    for p in (cpath, fpath):
        if os.path.exists(p):
            print("gen_idle_wraps: %s exists (never overwritten)" % p)
            return 2
    lines = ["/* generated by lift/harness/idle/gen_idle_wraps.py: do not edit. %d wrappers of the stubs of the runtime (decision 0129). */" % len(syms), "void idle_api_note(unsigned idx);", ""]
    for i, s in enumerate(syms):
        lines.append("void __real_%s(void);" % s)
        lines.append("void __wrap_%s(void) { idle_api_note(%du); __real_%s(); }" % (s, i, s))
    lines.append("")
    lines.append("const char *const idle_wrap_names[] = {")
    for s in syms:
        lines.append('    "%s",' % s[len(PREFIX):])
    lines.append("};")
    lines.append("const unsigned idle_wrap_count = %d;" % len(syms))
    with open(cpath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(fpath, "w", encoding="utf-8") as f:
        f.write(" ".join("-Wl,--wrap=%s" % s for s in syms) + "\n")
    print("gen_idle_wraps: %d wrappers -> %s, %s" % (len(syms), cpath, fpath))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
