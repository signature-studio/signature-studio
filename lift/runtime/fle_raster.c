/* ---- raster operations (Learn "Ternary Raster Operations" and "Binary Raster Operations") ---- */

int fle_r_rop3_valid(uint32_t code, uint32_t *idx)
{
    uint32_t i = code >> 16;

    if (code & 0xFF000000u) return 0;
    if (i > 0xFFu || rop3_code[i] != code) return 0;
    if (idx) *idx = i;
    return 1;
}

uint32_t fle_r_rop3_code(uint32_t idx) { return rop3_code[idx & 0xFFu]; }

/* The index is a truth table over (P, S, D): bit (P << 2 | S << 1 | D) of... the page defines the index as the result on the predefined values P = 0xF0, S = 0xCC, D = 0xAA, so bit k of the index is
 * the result for the operand bits that the bit k of those three values holds (P = bit k of 0xF0, S = bit k of 0xCC, D = bit k of 0xAA). */
static int rop3_bit(uint32_t idx, uint32_t p, uint32_t s, uint32_t d)
{
    uint32_t k = (p ? 4u : 0u) | (s ? 2u : 0u) | (d ? 1u : 0u);

    return (int)((idx >> k) & 1u);
}

int fle_r_idx_uses_source(uint32_t idx)
{
    for (uint32_t k = 0; k < 8; k++)
        if (rop3_bit(idx, (k >> 2) & 1u, (k >> 1) & 1u, k & 1u) != rop3_bit(idx, (k >> 2) & 1u, !((k >> 1) & 1u), k & 1u)) return 1;
    return 0;
}

int fle_r_idx_uses_pattern(uint32_t idx)
{
    for (uint32_t k = 0; k < 8; k++)
        if (rop3_bit(idx, (k >> 2) & 1u, (k >> 1) & 1u, k & 1u) != rop3_bit(idx, !((k >> 2) & 1u), (k >> 1) & 1u, k & 1u)) return 1;
    return 0;
}

int fle_r_idx_uses_dest(uint32_t idx)
{
    for (uint32_t k = 0; k < 8; k++)
        if (rop3_bit(idx, (k >> 2) & 1u, (k >> 1) & 1u, k & 1u) != rop3_bit(idx, (k >> 2) & 1u, (k >> 1) & 1u, !(k & 1u))) return 1;
    return 0;
}

uint32_t fle_r_rop3(uint32_t idx, uint32_t p, uint32_t s, uint32_t d)
{
    uint32_t r = 0;

    for (uint32_t k = 0; k < 8; k++) {
        if (!((idx >> k) & 1u)) continue;
        r |= ((k & 4u) ? p : ~p) & ((k & 2u) ? s : ~s) & ((k & 1u) ? d : ~d);
    }
    return r & 0xFFFFFFu;
}

/* The mix modes. SDK numbers (UNOFFICIAL): 1 R2_BLACK, 2 NOTMERGEPEN, 3 MASKNOTPEN, 4 NOTCOPYPEN, 5 MASKPENNOT, 6 NOT, 7 XORPEN, 8 NOTMASKPEN, 9 MASKPEN, 10 NOTXORPEN, 11 NOP, 12 MERGENOTPEN, 13 COPYPEN,
 * 14 MERGEPENNOT, 15 MERGEPEN, 16 WHITE. The Boolean operation of each is the one the page lists (Binary Raster Operations: R2_MASKNOTPEN DPna, R2_MASKPEN DPa, R2_MASKPENNOT PDna, R2_MERGENOTPEN DPno,
 * R2_MERGEPEN DPo, R2_MERGEPENNOT PDno, R2_NOT Dn, R2_NOTCOPYPEN Pn, R2_NOTMASKPEN DPan, R2_NOTMERGEPEN DPon, R2_NOTXORPEN DPxn, R2_XORPEN DPx; R2_BLACK 0, R2_WHITE 1, R2_COPYPEN P, R2_NOP D). */
int fle_r_rop2_valid(uint32_t mode) { return mode >= 1u && mode <= 16u; }

uint32_t fle_r_rop2(uint32_t mode, uint32_t p, uint32_t d)
{
    uint32_t r;

    switch (mode) {
    case 1: r = 0; break;
    case 2: r = ~(d | p); break;
    case 3: r = d & ~p; break;
    case 4: r = ~p; break;
    case 5: r = p & ~d; break;
    case 6: r = ~d; break;
    case 7: r = d ^ p; break;
    case 8: r = ~(d & p); break;
    case 9: r = d & p; break;
    case 10: r = ~(d ^ p); break;
    case 11: r = d; break;
    case 12: r = d | ~p; break;
    case 13: r = p; break;
    case 14: r = p | ~d; break;
    case 15: r = d | p; break;
    default: r = 0xFFFFFFu; break;
    }
    return r & 0xFFFFFFu;
}

/* ---- surfaces ---- */

uint8_t *fle_r_row(const fle_rsurf *s, uint32_t y)
{
    uint64_t r = s->bottom_up ? (uint64_t)s->height - 1u - y : y;

    return s->bits + r * s->stride;
}

int fle_r_direct(const fle_rsurf *s)
{
    if (!s->bits) return 0;
    if (s->bpp == 24) return s->comp == 0;
    if (s->bpp == 32) return s->comp == 0 || (s->comp == 3 && s->masks[0] == 0x00FF0000u && s->masks[1] == 0x0000FF00u && s->masks[2] == 0x000000FFu);
    return 0;
}

int fle_r_writable(const fle_rsurf *s)
{
    return fle_r_direct(s) || (s->bits && s->bpp == 1 && s->comp == 0);
}

int fle_r_readable(const fle_rsurf *s)
{
    if (fle_r_direct(s)) return 1;
    return s->bits && (s->bpp == 8 || s->bpp == 4 || s->bpp == 1) && s->comp == 0 && s->ncolors > 0 && s->clr;
}

int fle_r_same_format(const fle_rsurf *a, const fle_rsurf *b)
{
    if (a->bpp != b->bpp || a->comp != b->comp) return 0;
    for (uint32_t i = 0; i < 3; i++)
        if (a->masks[i] != b->masks[i]) return 0;
    if (a->bpp <= 8) {
        if (a->ncolors != b->ncolors) return 0;
        for (uint32_t i = 0; i < a->ncolors; i++)
            if (a->clr[i] != b->clr[i]) return 0;
    }
    return 1;
}

uint32_t fle_r_get(const fle_rsurf *s, uint32_t x, uint32_t y)
{
    const uint8_t *p = fle_r_row(s, y);

    if (s->bpp <= 8) {
        uint32_t i, c;

        if (s->bpp == 8) i = p[x];
        else if (s->bpp == 4) i = (p[x >> 1] >> ((x & 1u) ? 0 : 4)) & 0xFu;
        else i = (p[x >> 3] >> (7u - (x & 7u))) & 1u;
        c = i < s->ncolors ? s->clr[i] : 0u;
        return ((c & 0xFFu) << 16) | (c & 0xFF00u) | ((c >> 16) & 0xFFu);
    }
    p += (uint64_t)x * (s->bpp / 8u);
    return (uint32_t)p[2] | ((uint32_t)p[1] << 8) | ((uint32_t)p[0] << 16);
}

void fle_r_put(const fle_rsurf *s, uint32_t x, uint32_t y, uint32_t cref)
{
    uint32_t n = s->bpp / 8u;
    uint8_t *p;

    if (s->bpp == 1) {
        uint8_t *q = fle_r_row(s, y) + (x >> 3), m = (uint8_t)(0x80u >> (x & 7u));

        if (cref & 0xFFFFFFu) *q |= m;
        else *q &= (uint8_t)~m;
        return;
    }
    p = fle_r_row(s, y) + (uint64_t)x * n;

    p[0] = (uint8_t)(cref >> 16);
    p[1] = (uint8_t)(cref >> 8);
    p[2] = (uint8_t)cref;
    if (n == 4) p[3] = 0;
}

fle_rrect fle_r_bounds(const fle_rsurf *s)
{
    fle_rrect r = { 0, 0, (int64_t)s->width, (int64_t)s->height };

    return r;
}

void fle_r_clip(fle_rrect *r, const fle_rrect *c)
{
    if (r->x0 < c->x0) r->x0 = c->x0;
    if (r->y0 < c->y0) r->y0 = c->y0;
    if (r->x1 > c->x1) r->x1 = c->x1;
    if (r->y1 > c->y1) r->y1 = c->y1;
    if (r->x1 < r->x0) r->x1 = r->x0;
    if (r->y1 < r->y0) r->y1 = r->y0;
}

int fle_r_empty(const fle_rrect *r) { return r->x1 <= r->x0 || r->y1 <= r->y0; }

static fle_rrect eff_clip(const fle_rsurf *d, const fle_rrect *clip)
{
    fle_rrect c = fle_r_bounds(d);

    if (clip) fle_r_clip(&c, clip);
    return c;
}

/* ---- the operations ---- */

uint64_t fle_r_rop_rect(const fle_rsurf *d, const fle_rrect *clip, fle_rrect r, uint32_t idx, uint32_t pat)
{
    fle_rrect c = eff_clip(d, clip);
    int ud = fle_r_idx_uses_dest(idx);
    uint64_t n = 0;

    fle_r_clip(&r, &c);
    if (fle_r_empty(&r)) return 0;
    for (int64_t y = r.y0; y < r.y1; y++)
        for (int64_t x = r.x0; x < r.x1; x++) {
            uint32_t dc = ud ? fle_r_get(d, (uint32_t)x, (uint32_t)y) : 0u;

            fle_r_put(d, (uint32_t)x, (uint32_t)y, fle_r_rop3(idx, pat, 0u, dc));
            n++;
        }
    return n;
}

uint64_t fle_r_mix_rect(const fle_rsurf *d, const fle_rrect *clip, fle_rrect r, uint32_t rop2, uint32_t pen)
{
    fle_rrect c = eff_clip(d, clip);
    uint64_t n = 0;

    fle_r_clip(&r, &c);
    if (fle_r_empty(&r) || rop2 == 11u) return 0;
    for (int64_t y = r.y0; y < r.y1; y++)
        for (int64_t x = r.x0; x < r.x1; x++) {
            fle_r_put(d, (uint32_t)x, (uint32_t)y, fle_r_rop2(rop2, pen, fle_r_get(d, (uint32_t)x, (uint32_t)y)));
            n++;
        }
    return n;
}

/* The colour of the source pixel (x, y) as the destination `d` takes it: the conversions of the monochrome and colour surfaces (the fields of fle_rsurf). */
static uint32_t src_color(const fle_rsurf *d, const fle_rsurf *s, int64_t x, int64_t y)
{
    uint32_t c = fle_r_get(s, (uint32_t)x, (uint32_t)y);

    if (s->bpp == 1 && d->bpp != 1 && s->conv_set) return c ? s->conv_bg : s->conv_fg;
    if (d->bpp == 1 && s->bpp != 1 && d->mono_key_set) return c == d->mono_key ? 0xFFFFFFu : 0u;
    return c;
}

/* Decision 0245 (alpha2) and its addendum (alpha2b): did a run of fle_r_blit calls change the destination? The caller (fle_gdi.c, for a window surface) calls fle_r_changed_begin(), makes its fle_r_blit calls, and asks
 * fle_r_changed(&r): 0 when every call compared its bytes with the destination while it wrote and none differed (the surface is exactly as it was: nothing is to be told to the compositor), else 1 with r narrowed to
 * [the first row that differed, the end of the call that found it) and to the rows of the calls after it (when a call could not compare, r stays as it was). Only the plain copies compare (SRCCOPY between two 32-bit
 * surfaces, the two paths below), in the same pass that writes: a load of the destination word and an OR of the difference. Addendum alpha2b: once a row has differed the answer is "changed" whatever follows, so the
 * rest of that call, and every later call of the run, is copied as before (no load of the destination, no OR): the cost of a copy that changes the picture is the cost without the comparison, except for the rows up to
 * the first one that differs. Any other call of the run (another raster operation, another format, a copy inside one surface) sets "unknown". With no begin the calls compare nothing and cost what they cost before. */
static int ch_active, ch_unknown, ch_any;
static int64_t ch_y0, ch_y1;

void fle_r_changed_begin(void)
{
    ch_active = 1;
    ch_unknown = 0;
    ch_any = 0;
}

int fle_r_changed(fle_rrect *r)
{
    int unknown = ch_unknown, any = ch_any;
    int64_t y0 = ch_y0, y1 = ch_y1;

    ch_active = 0;
    if (unknown) return 1;
    if (!any) return 0;
    if (y0 > r->y0) r->y0 = y0;
    if (y1 < r->y1) r->y1 = y1;
    return 1;
}

/* rows [y0, y1) may have changed: the first row that differed up to the end of its call, or a whole later call */
static void ch_rows(int64_t y0, int64_t y1)
{
    if (!ch_any || y0 < ch_y0) ch_y0 = y0;
    if (!ch_any || y1 > ch_y1) ch_y1 = y1;
    ch_any = 1;
}

/* A copy with a ternary operation. The source rectangle must lie inside the source surface (the caller checks: BitBlt "only does clipping on the destination DC"). The same surface as source and destination
 * is handled like memmove: the rows (and, in a row, the columns) are visited in the direction that does not overwrite what is still to be read. The unused byte of a 32-bit pixel is copied by a plain SRCCOPY
 * between two surfaces of the same format (bytes, decision 0111) and is 0 otherwise. */
uint64_t fle_r_blit(const fle_rsurf *d, const fle_rrect *clip, int64_t dx, int64_t dy, int64_t w, int64_t h, const fle_rsurf *s, int64_t sx, int64_t sy, uint32_t idx, uint32_t pat)
{
    fle_rrect c = eff_clip(d, clip), r = { dx, dy, dx + w, dy + h };
    int same_surface = s && d->bits == s->bits;
    int bytes = s && idx == FLE_R_SRCCOPY_IDX && fle_r_same_format(d, s) && d->bpp >= 8 && (d->bpp != 32 || (d->keep_x && s->keep_x));
    /* decision 0203 (always on since decision 0243): SRCCOPY between two direct 32-bit surfaces when `bytes` is false (a window surface or a DDB has no X byte to keep): the pixel loop below reads the three colour bytes
     * of the source pixel (fle_r_get: bytes 2, 1, 0) and writes them back (fle_r_put: bytes 0, 1, 2 and byte 3 = 0), i.e. dst = src & 0x00FFFFFF bytewise, whatever the masks of the two formats are (get/put ignore them).
     * The same walk (rows bottom-up when `down`, columns right-to-left when `back`) keeps the memmove behaviour of a copy inside one surface. */
    int fast = s && !bytes && idx == FLE_R_SRCCOPY_IDX && d->bpp == 32 && s->bpp == 32 && fle_r_direct(d) && fle_r_direct(s);
    int us = fle_r_idx_uses_source(idx), ud = fle_r_idx_uses_dest(idx);
    int down = same_surface && dy > sy;
    int back = same_surface && dy == sy && dx > sx;
    uint64_t n = 0;
    int cmp;   /* decision 0245: this call compares what it writes (see fle_r_changed) */

    fle_r_clip(&r, &c);
    if (fle_r_empty(&r)) return 0;
    cmp = ch_active && !same_surface && d->bpp == 32 && (bytes || fast);
    if (ch_active && !cmp) ch_unknown = 1;
    if (cmp && ch_any) ch_rows(r.y0, r.y1);   /* alpha2b: a row has differed already: this call is copied as before and is all "may have changed" */
    for (int64_t i = 0; i < r.y1 - r.y0; i++) {
        int64_t y = down ? r.y1 - 1 - i : r.y0 + i;
        int64_t sy_ = sy + (y - dy);

        if (bytes && cmp && !ch_any) {
            uint32_t *to = (uint32_t *)(void *)(fle_r_row(d, (uint32_t)y) + (uint64_t)r.x0 * 4u), acc = 0;
            const uint8_t *from = fle_r_row(s, (uint32_t)sy_) + (uint64_t)(sx + (r.x0 - dx)) * 4u;
            int64_t cnt = r.x1 - r.x0;

            for (int64_t k = 0; k < cnt; k++) {
                uint32_t v, o;

                memcpy(&v, from + (uint64_t)k * 4u, 4);
                memcpy(&o, to + k, 4);
                acc |= o ^ v;
                memcpy(to + k, &v, 4);
            }
            if (acc) ch_rows(y, r.y1);
            n += (uint64_t)cnt;
            continue;
        }
        if (bytes) {
            uint32_t nb = d->bpp / 8u;
            uint8_t *to = fle_r_row(d, (uint32_t)y) + (uint64_t)r.x0 * nb;
            const uint8_t *from = fle_r_row(s, (uint32_t)sy_) + (uint64_t)(sx + (r.x0 - dx)) * nb;

            memmove(to, from, (size_t)(r.x1 - r.x0) * nb);
            n += (uint64_t)(r.x1 - r.x0);
            continue;
        }
        if (fast && cmp && !ch_any) {
            static const uint8_t keep3c[4] = { 0xFFu, 0xFFu, 0xFFu, 0x00u };
            uint32_t m, acc = 0;
            int64_t cnt = r.x1 - r.x0;
            uint32_t *to = (uint32_t *)(void *)(fle_r_row(d, (uint32_t)y) + (uint64_t)r.x0 * 4u);
            const uint8_t *from = fle_r_row(s, (uint32_t)sy_) + (uint64_t)(sx + (r.x0 - dx)) * 4u;

            memcpy(&m, keep3c, 4);
            for (int64_t k = 0; k < cnt; k++) {
                uint32_t v, o;

                memcpy(&v, from + (uint64_t)k * 4u, 4);
                v &= m;
                memcpy(&o, to + k, 4);
                acc |= o ^ v;
                memcpy(to + k, &v, 4);
            }
            if (acc) ch_rows(y, r.y1);
            n += (uint64_t)cnt;
            continue;
        }
        if (fast) {
            static const uint8_t keep3[4] = { 0xFFu, 0xFFu, 0xFFu, 0x00u };
            uint32_t m, v;
            int64_t cnt = r.x1 - r.x0;
            uint8_t *to = fle_r_row(d, (uint32_t)y) + (uint64_t)r.x0 * 4u;
            const uint8_t *from = fle_r_row(s, (uint32_t)sy_) + (uint64_t)(sx + (r.x0 - dx)) * 4u;

            memcpy(&m, keep3, 4);
            if (back) {
                for (int64_t k = cnt - 1; k >= 0; k--) { memcpy(&v, from + (uint64_t)k * 4u, 4); v &= m; memcpy(to + (uint64_t)k * 4u, &v, 4); }
            } else {
                for (int64_t k = 0; k < cnt; k++) { memcpy(&v, from + (uint64_t)k * 4u, 4); v &= m; memcpy(to + (uint64_t)k * 4u, &v, 4); }
            }
            n += (uint64_t)cnt;
            continue;
        }
        for (int64_t k = 0; k < r.x1 - r.x0; k++) {
            int64_t x = back ? r.x1 - 1 - k : r.x0 + k;
            uint32_t sc = 0, dc = 0;

            if (us) sc = src_color(d, s, sx + (x - dx), sy_);
            if (ud) dc = fle_r_get(d, (uint32_t)x, (uint32_t)y);
            fle_r_put(d, (uint32_t)x, (uint32_t)y, fle_r_rop3(idx, pat, sc, dc));
            n++;
        }
    }
    return n;
}

/* MaskBlt: the same walk as fle_r_blit with one ternary operation per pixel chosen by the mask bit ("A value of 1 in the mask ... indicates that the foreground raster operation code ... should be applied at that
 * location. A value of 0 ... the background"). The caller has checked that the mask covers the rectangle and that the source rectangle is inside the source. The overlapping case of one surface as source and destination
 * is handled as in fle_r_blit. */
uint64_t fle_r_maskblt(const fle_rsurf *d, const fle_rrect *clip, int64_t dx, int64_t dy, int64_t w, int64_t h, const fle_rsurf *s, int64_t sx, int64_t sy, const fle_rsurf *mask, int64_t mx, int64_t my, uint32_t fg, uint32_t bg, uint32_t pat)
{
    fle_rrect c = eff_clip(d, clip), r = { dx, dy, dx + w, dy + h };
    int same_surface = s && d->bits == s->bits;
    int down = same_surface && dy > sy;
    int back = same_surface && dy == sy && dx > sx;
    int us = fle_r_idx_uses_source(fg) || fle_r_idx_uses_source(bg);
    uint64_t n = 0;

    fle_r_clip(&r, &c);
    if (fle_r_empty(&r)) return 0;
    for (int64_t i = 0; i < r.y1 - r.y0; i++) {
        int64_t y = down ? r.y1 - 1 - i : r.y0 + i;

        for (int64_t k = 0; k < r.x1 - r.x0; k++) {
            int64_t x = back ? r.x1 - 1 - k : r.x0 + k;
            uint32_t m = fle_r_get(mask, (uint32_t)(mx + (x - dx)), (uint32_t)(my + (y - dy)));
            uint32_t idx = m ? fg : bg, sc = 0, dc = 0;

            if (us && fle_r_idx_uses_source(idx)) sc = src_color(d, s, sx + (x - dx), sy + (y - dy));
            if (fle_r_idx_uses_dest(idx)) dc = fle_r_get(d, (uint32_t)x, (uint32_t)y);
            fle_r_put(d, (uint32_t)x, (uint32_t)y, fle_r_rop3(idx, pat, sc, dc));
            n++;
        }
    }
    return n;
}

/* Stretching: the source rectangle (sx, sy, sw, sh) is mapped onto the destination rectangle (dx, dy, dw, dh); a negative extent is the mirror image (Learn StretchBlt: "If nWidthSrc and nWidthDest have
 * different signs, the function creates a mirror image"). Destination pixel i of a row covers the source columns [floor(i * |sw| / |dw|), floor((i + 1) * |sw| / |dw|)) of the source rectangle (at least one:
 * when enlarging a source pixel is repeated, "the pixel the centre falls on"); likewise for rows (S-stretch-groups: the pages do not say which source pixels a destination pixel stands for). When a group has
 * more than one pixel (a shrink) the stretching mode of the DC decides (Learn SetStretchBltMode): BLACKONWHITE "Performs a Boolean AND operation using the color values for the eliminated and existing pixels",
 * WHITEONBLACK the OR, COLORONCOLOR "Deletes the pixels" (the pixel under the centre of the destination pixel is kept), HALFTONE "The average color over the destination block of pixels approximates the color of the
 * source pixels" (S-stretch-halftone: the arithmetic mean of each colour channel of the group; the brush origin and the dithering of the real HALFTONE are not modelled). Source rectangles are inside the source. */
static uint32_t stretch_color(const fle_rsurf *d, const fle_rsurf *s, int64_t qx, int64_t qy, int64_t gx0, int64_t gx1, int64_t gy0, int64_t gy1, int64_t cx, int64_t cy, uint32_t mode)
{
    uint64_t n = 0, sr = 0, sg = 0, sb = 0;
    uint32_t acc = mode == 2 ? 0u : 0xFFFFFFu;

    if ((gx1 - gx0) * (gy1 - gy0) <= 1 || mode == 3) return src_color(d, s, qx + cx, qy + cy);
    for (int64_t y = gy0; y < gy1; y++)
        for (int64_t x = gx0; x < gx1; x++) {
            uint32_t c = src_color(d, s, qx + x, qy + y);

            if (mode == 1) acc &= c;
            else if (mode == 2) acc |= c;
            else {
                sr += c & 0xFFu;
                sg += (c >> 8) & 0xFFu;
                sb += (c >> 16) & 0xFFu;
                n++;
            }
        }
    if (mode == 1 || mode == 2) return acc;
    return (uint32_t)(sr / n) | ((uint32_t)(sg / n) << 8) | ((uint32_t)(sb / n) << 16);
}

uint64_t fle_r_stretch(const fle_rsurf *d, const fle_rrect *clip, int64_t dx, int64_t dy, int64_t dw, int64_t dh, const fle_rsurf *s, int64_t sx, int64_t sy, int64_t sw, int64_t sh, uint32_t idx, uint32_t pat, uint32_t mode)
{
    fle_rrect c = eff_clip(d, clip);
    int64_t adw = dw < 0 ? -dw : dw, adh = dh < 0 ? -dh : dh, asw = sw < 0 ? -sw : sw, ash = sh < 0 ? -sh : sh;
    int64_t ox = dw < 0 ? dx + dw : dx, oy = dh < 0 ? dy + dh : dy;         /* the destination rectangle, normalized */
    int64_t qx = sw < 0 ? sx + sw : sx, qy = sh < 0 ? sy + sh : sy;         /* the source rectangle, normalized */
    int mx = (dw < 0) != (sw < 0), my = (dh < 0) != (sh < 0);
    int us = fle_r_idx_uses_source(idx), ud = fle_r_idx_uses_dest(idx);
    fle_rrect r = { ox, oy, ox + adw, oy + adh };
    uint64_t n = 0;

    if (adw == 0 || adh == 0 || asw == 0 || ash == 0) return 0;
    fle_r_clip(&r, &c);
    if (fle_r_empty(&r)) return 0;
    for (int64_t y = r.y0; y < r.y1; y++) {
        int64_t iy = y - oy, gy0 = (iy * ash) / adh, gy1 = ((iy + 1) * ash) / adh, cy;

        if (gy1 <= gy0) gy1 = gy0 + 1;
        cy = ((2 * iy + 1) * ash) / (2 * adh);
        if (my) {
            int64_t t0 = ash - gy1, t1 = ash - gy0;

            gy0 = t0;
            gy1 = t1;
            cy = ash - 1 - cy;
        }
        for (int64_t x = r.x0; x < r.x1; x++) {
            int64_t ix = x - ox, gx0 = (ix * asw) / adw, gx1 = ((ix + 1) * asw) / adw, cx;
            uint32_t sc = 0, dcol = 0;

            if (gx1 <= gx0) gx1 = gx0 + 1;
            cx = ((2 * ix + 1) * asw) / (2 * adw);
            if (mx) {
                int64_t t0 = asw - gx1, t1 = asw - gx0;

                gx0 = t0;
                gx1 = t1;
                cx = asw - 1 - cx;
            }
            if (us) sc = stretch_color(d, s, qx, qy, gx0, gx1, gy0, gy1, cx, cy, mode);
            if (ud) dcol = fle_r_get(d, (uint32_t)x, (uint32_t)y);
            fle_r_put(d, (uint32_t)x, (uint32_t)y, fle_r_rop3(idx, pat, sc, dcol));
            n++;
        }
    }
    return n;
}

/* A one-pixel line from (x0, y0) up to, but not including, (x1, y1) (Learn LineTo: "up to, but not including, the specified point"; Lines: "The pixel located at the starting point is always included in the line, and
 * the pixel located at the ending point is always excluded"). Which pixels the GDI DDA picks between the two points is not on the pages ("a modified Bresenham ... does not round off to the nearest integer"):
 * S-line-dda: the integer Bresenham line of the longer axis, ties of the error term resolved toward the start, i.e. the pixel (x, y) with y = y0 + round_half_down((x - x0) * dy / dx) on an x-major line. */
uint64_t fle_r_line(const fle_rsurf *d, const fle_rrect *clip, int64_t x0, int64_t y0, int64_t x1, int64_t y1, uint32_t pen, uint32_t rop2)
{
    fle_rrect c = eff_clip(d, clip);
    int64_t dx = x1 - x0, dy = y1 - y0, adx = dx < 0 ? -dx : dx, ady = dy < 0 ? -dy : dy, len = adx > ady ? adx : ady;
    uint64_t n = 0;

    if (len == 0) return 0;
    if (len > FLE_R_LINE_MAX) return 0;
    for (int64_t i = 0; i < len; i++) {
        int64_t x, y;

        if (adx >= ady) {
            int64_t t = i * ady, q = t / adx, rem = t % adx;

            if (2 * rem > adx) q++;
            x = x0 + (dx < 0 ? -i : i);
            y = y0 + (dy < 0 ? -q : q);
        } else {
            int64_t t = i * adx, q = t / ady, rem = t % ady;

            if (2 * rem > ady) q++;
            y = y0 + (dy < 0 ? -i : i);
            x = x0 + (dx < 0 ? -q : q);
        }
        if (x < c.x0 || x >= c.x1 || y < c.y0 || y >= c.y1) continue;
        if (rop2 != 11u) fle_r_put(d, (uint32_t)x, (uint32_t)y, fle_r_rop2(rop2, pen, fle_r_get(d, (uint32_t)x, (uint32_t)y)));
        n++;
    }
    return n;
}

/* ---- the drawing surfaces of top-level windows (R10 of docs/investigations/detach-window.md) ---- */

#define SURF_MAX_DIM 16384u

typedef struct {
    uint32_t lid;
    uint8_t live;
    uint32_t w, h;
    uint8_t *bits;
    fle_rsurf view;
    uint64_t writes, discards;
    int first_done;
} wsurf;

static wsurf **ws;                          /* each surface is its own allocation: a pointer to its view stays valid while others are made */
static uint32_t ws_n, ws_cap;
static uint64_t discarded_total;
static int discard_logged;
static int evidence_seen;
static char *evidence_text;

uint32_t fle_raster_surface_count(void)
{
    uint32_t n = 0;

    for (uint32_t i = 0; i < ws_n; i++) n += ws[i]->live;
    return n;
}

uint64_t fle_raster_discarded_count(void) { return discarded_total; }
int fle_raster_evidence_seen(void) { return evidence_seen; }

static wsurf *ws_find(uint32_t lid)
{
    for (uint32_t i = 0; i < ws_n; i++)
        if (ws[i]->live && ws[i]->lid == lid) return ws[i];
    return NULL;
}

static void ws_fill_view(wsurf *s)
{
    memset(&s->view, 0, sizeof s->view);
    s->view.bits = s->bits;
    s->view.width = s->w;
    s->view.height = s->h;
    s->view.stride = s->w * 4u;
    s->view.bpp = 32;
    s->view.comp = 0;
    s->view.bottom_up = 0;
}

/* Made on first use; the pixels start as zero bytes (S-surface-init: the pages give no initial content for a window; zero is "black, unused byte 0" and is the colour the evidence rule calls background). A
 * window of another size than the surface it asks for keeps the overlapping pixels (a size change must not erase what was drawn: a choice, S-surface-resize). */
fle_rsurf *fle_raster_window_surface(uint32_t lid, uint32_t w, uint32_t h)
{
    wsurf *s = ws_find(lid);
    uint64_t bytes;
    uint8_t *nb;

    if (w == 0 || h == 0 || w > SURF_MAX_DIM || h > SURF_MAX_DIM) return NULL;
    bytes = (uint64_t)w * h * 4u;
    if (bytes >= UINT64_C(0x80000000)) return NULL;
    if (s && s->w == w && s->h == h) return &s->view;
    nb = (uint8_t *)calloc(1, (size_t)bytes);
    if (!nb) return NULL;
    if (s) {
        uint32_t cw = s->w < w ? s->w : w, ch = s->h < h ? s->h : h;

        for (uint32_t y = 0; y < ch; y++) memcpy(nb + (uint64_t)y * w * 4u, s->bits + (uint64_t)y * s->w * 4u, (size_t)cw * 4u);
        free(s->bits);
    } else {
        if (ws_n == ws_cap) {
            uint32_t nc = ws_cap ? ws_cap * 2u : 8u;
            wsurf **n = (wsurf **)realloc(ws, (size_t)nc * sizeof *ws);

            if (!n) {
                free(nb);
                return NULL;
            }
            ws = n;
            ws_cap = nc;
        }
        s = (wsurf *)calloc(1, sizeof *s);
        if (!s) {
            free(nb);
            return NULL;
        }
        ws[ws_n++] = s;
        s->lid = lid;
        s->live = 1;
    }
    s->bits = nb;
    s->w = w;
    s->h = h;
    ws_fill_view(s);
    return &s->view;
}

void fle_raster_window_destroyed(uint32_t lid)
{
    wsurf *s = ws_find(lid);

    if (!s) return;
    free(s->bits);
    s->bits = NULL;
    s->live = 0;
}

const fle_rsurf *fle_raster_surface_peek(uint32_t lid)
{
    wsurf *s = ws_find(lid);

    return s ? &s->view : NULL;
}

uint64_t fle_raster_nonzero_pixels(const fle_rsurf *s)
{
    uint64_t n = 0;

    if (!s || !s->bits || (s->bpp != 32 && s->bpp != 24)) return 0;
    for (uint32_t y = 0; y < s->height; y++) {
        const uint8_t *p = fle_r_row(s, y);

        for (uint32_t x = 0; x < s->width; x++, p += s->bpp / 8u)
            if (p[0] | p[1] | p[2]) n++;
    }
    return n;
}

typedef struct { uint32_t color; uint64_t n; } hist_ent;

static int hist_cmp(const void *a, const void *b)
{
    const hist_ent *x = (const hist_ent *)a, *y = (const hist_ent *)b;

    if (x->n != y->n) return x->n < y->n ? 1 : -1;
    return x->color < y->color ? -1 : x->color > y->color;
}

/* The histogram of the colours of a surface (COLORREF) in a table that doubles: returns the number of distinct colours and sorts the table by count, then by colour. */
static uint32_t histogram(const fle_rsurf *s, hist_ent **out)
{
    uint32_t cap = 1024, n = 0;
    hist_ent *t = (hist_ent *)calloc(cap, sizeof *t);
    uint32_t *slot = (uint32_t *)malloc((size_t)cap * 2u * sizeof *slot);
    uint32_t mask = cap * 2u - 1u;

    *out = NULL;
    if (!t || !slot) {
        free(t);
        free(slot);
        return 0;
    }
    memset(slot, 0xFF, (size_t)cap * 2u * sizeof *slot);
    for (uint32_t y = 0; y < s->height; y++)
        for (uint32_t x = 0; x < s->width; x++) {
            uint32_t c = fle_r_get(s, x, y), h = (c * 2654435761u) & mask;

            while (slot[h] != 0xFFFFFFFFu && t[slot[h]].color != c) h = (h + 1u) & mask;
            if (slot[h] == 0xFFFFFFFFu) {
                if (n == cap) {
                    hist_ent *nt = (hist_ent *)realloc(t, (size_t)cap * 2u * sizeof *t);
                    uint32_t *ns;

                    if (!nt) break;
                    t = nt;
                    cap *= 2u;
                    ns = (uint32_t *)realloc(slot, (size_t)cap * 2u * sizeof *slot);
                    if (!ns) break;
                    slot = ns;
                    mask = cap * 2u - 1u;
                    memset(slot, 0xFF, (size_t)cap * 2u * sizeof *slot);
                    for (uint32_t k = 0; k < n; k++) {
                        uint32_t hh = (t[k].color * 2654435761u) & mask;

                        while (slot[hh] != 0xFFFFFFFFu) hh = (hh + 1u) & mask;
                        slot[hh] = k;
                    }
                    h = (c * 2654435761u) & mask;
                    while (slot[h] != 0xFFFFFFFFu) h = (h + 1u) & mask;
                }
                t[n].color = c;
                t[n].n = 0;
                slot[h] = n++;
            }
            t[slot[h]].n++;
        }
    free(slot);
    qsort(t, n, sizeof *t, hist_cmp);
    *out = t;
    return n;
}

static int describe_view(FILE *f, uint32_t lid, const fle_rsurf *s, uint64_t writes)
{
    hist_ent *h = NULL;
    uint32_t nd = histogram(s, &h);
    uint64_t nz = fle_raster_nonzero_pixels(s);

    fprintf(f, "  surface of top-level window lid %u: %u x %u (BGRX 32-bit top-down), calls that wrote %" PRIu64 ", non-zero pixels %" PRIu64 " of %" PRIu64 ", distinct colours %u; top colours (COLORREF 0xBBGGRR: count):",
            (unsigned)lid, (unsigned)s->width, (unsigned)s->height, writes, nz, (uint64_t)s->width * s->height, (unsigned)nd);
    for (uint32_t k = 0; h && k < nd && k < 8u; k++) fprintf(f, " %#08x:%" PRIu64, (unsigned)h[k].color, h[k].n);
    fprintf(f, "\n");
    free(h);
    return 1;
}

int fle_raster_describe(FILE *f, uint32_t lid)
{
    wsurf *s = ws_find(lid);

    if (!s) return 0;
    return describe_view(f, lid, &s->view, s->writes);
}

void fle_raster_report(FILE *f)
{
    fprintf(f, "drawing surfaces (decision 0126): %u live, drawing calls discarded because the window was not visible %" PRIu64 "\n", (unsigned)fle_raster_surface_count(), discarded_total);
    for (uint32_t i = 0; i < ws_n; i++)
        if (ws[i]->live) describe_view(f, ws[i]->lid, &ws[i]->view, ws[i]->writes);
    if (evidence_text) fputs(evidence_text, f);
}

/* The first non-background pixel: when a window surface holds, for the first time, a pixel whose three colour bytes are not all 0 after a write, the window table and the summary of the surface are written (once
 * per run; the first surface only: a later surface's first pixel is not "the first"). */
void fle_raster_discarded(const char *api, uint32_t lid)
{
    discarded_total++;
    if (!discard_logged) {
        discard_logged = 1;
        fprintf(stderr, "first drawing call discarded because its window is not visible (decision 0126, S-draw-hidden): %s into the surface of top-level window lid %u; function entries since the program began: %" PRIu64 "\n",
                api ? api : "?", (unsigned)lid, trace_call_count ? trace_call_count() : (uint64_t)0);
    }
}

void fle_raster_wrote(const fle_rsurf *surf, fle_rrect r, const char *api)
{
    wsurf *s = NULL;
    char *buf = NULL;
    size_t len = 0;
    FILE *m;
    int any = 0;

    for (uint32_t i = 0; i < ws_n; i++)
        if (ws[i]->live && &ws[i]->view == surf) s = ws[i];
    if (!s) return;
    s->writes++;
    if (fle_desk_wrote) fle_desk_wrote(s->lid, r.x0, r.y0, r.x1, r.y1);   /* decision 0223: the desktop compositor (fle_desk.c) learns which part of a window's picture changed */
    if (evidence_seen || s->first_done) return;
    fle_r_clip(&r, &(fle_rrect){ 0, 0, (int64_t)s->w, (int64_t)s->h });
    for (int64_t y = r.y0; y < r.y1 && !any; y++) {
        const uint8_t *p = fle_r_row(&s->view, (uint32_t)y) + (uint64_t)r.x0 * 4u;

        for (int64_t x = r.x0; x < r.x1; x++, p += 4)
            if (p[0] | p[1] | p[2]) {
                any = 1;
                break;
            }
    }
    if (!any) return;
    s->first_done = 1;
    evidence_seen = 1;
    m = open_memstream(&buf, &len);
    if (!m) return;
    fprintf(m, "first non-background pixel on a drawing surface (decision 0126): written by %s into the surface of top-level window lid %u; function entries since the program began: %" PRIu64 "\n",
            api ? api : "?", (unsigned)s->lid, trace_call_count ? trace_call_count() : (uint64_t)0);
    describe_view(m, s->lid, &s->view, s->writes);
    if (fle_win_table_report) fle_win_table_report(m);
    fclose(m);
    evidence_text = buf;
    fputs(buf, stderr);
}

/* Decision 0129 (idle continuation): the logical ids of the live window surfaces, in the order the surfaces were made (at most `cap`); returns the number written. For the state signature of the harness (a hash of
 * every surface); it moves no state. */
uint32_t fle_raster_live_lids(uint32_t *out, uint32_t cap)
{
    uint32_t n = 0;

    for (uint32_t i = 0; i < ws_n && n < cap; i++)
        if (ws[i]->live) out[n++] = ws[i]->lid;
    return n;
}
