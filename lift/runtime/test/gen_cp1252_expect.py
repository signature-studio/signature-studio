#!/usr/bin/env python3
"""Writes the expected byte -> UTF-16 table of code page 1252 for tests/locale.rs (decision 0084), independent of
runtime/fle_locale.c.

usage: gen_cp1252_expect.py DATAFILES.zip OUT.txt

DATAFILES.zip: "Windows Supported Code Page Data Files.zip" (Microsoft Download Center id=10921; [CODEPAGEFILES] of
[MS-UCODEREF] 1.2.1). Both SHA-256 values below are checked first. OUT.txt must not exist (it is never overwritten).
Only the Python standard library is used. The zip is a gitignored work file: the tests read OUT.txt
(lift/runtime/test/cp1252_expect.txt), not the zip.
Reproduce:  python3 lift/runtime/test/gen_cp1252_expect.py lift/out-mbtwc/ref/Windows_Supported_Code_Page_Data_Files.zip OUT.txt
"""
import hashlib
import io
import sys
import zipfile

ZIP_SHA256 = "5074e6dd253056ba61fc6c870c9a955467855129c6ad3a51761c386b301b125a"
MEMBER = "CodpageFiles/1252.txt"
MEMBER_SHA256 = "72ea23c939c5b26fae7aded0207b327e2f3902d7d3c168d7087f5cfc38ee76a9"


def mbtable(text: str) -> dict:
    """The byte -> code point rows of the MBTABLE section ([MS-UCODEREF] 2.2.2.1.2)."""
    lines = [l.split(";")[0].strip() for l in text.replace("\r", "").split("\n")]
    start = lines.index("MBTABLE 256")
    rows = {}
    for l in lines[start + 1 :]:
        if not l:
            continue
        if not l.startswith("0x"):
            break  # next section tag (WCTABLE)
        b, u = l.split()
        b, u = int(b, 16), int(u, 16)
        if b in rows or not (0 <= b <= 255 and 0 <= u <= 0xFFFF):
            raise SystemExit("bad MBTABLE row: " + l)
        rows[b] = u
    if sorted(rows) != list(range(256)):
        raise SystemExit("MBTABLE does not have exactly the bytes 0x00..0xFF")
    return rows


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 64
    zpath, out = sys.argv[1], sys.argv[2]
    zbytes = open(zpath, "rb").read()
    if hashlib.sha256(zbytes).hexdigest() != ZIP_SHA256:
        print("zip SHA-256 differs from the one in decision 0084", file=sys.stderr)
        return 1
    raw = zipfile.ZipFile(io.BytesIO(zbytes)).read(MEMBER)
    if hashlib.sha256(raw).hexdigest() != MEMBER_SHA256:
        print(MEMBER + " SHA-256 differs from the one in decision 0084", file=sys.stderr)
        return 1
    rows = mbtable(raw.decode("ascii"))
    with open(out, "x") as f:
        f.write("# GENERATED by lift/runtime/test/gen_cp1252_expect.py (decision 0084). Do not edit.\n")
        f.write("# Expected MultiByteToWideChar result for each byte of code page 1252: the MBTABLE section of " + MEMBER + "\n")
        f.write("# in \"Windows Supported Code Page Data Files.zip\" (zip SHA-256 " + ZIP_SHA256 + ",\n")
        f.write("# " + MEMBER + " SHA-256 " + MEMBER_SHA256 + "). One row per byte: byte, UTF-16 unit.\n")
        for b in range(256):
            f.write("0x%02X 0x%04X\n" % (b, rows[b]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
