#!/usr/bin/env python3
"""Decision 0209 (crash1): lift/runtime/fle_crash1_case.inc from the Unicode Character Database 16.0.0 UnicodeData.txt (unicode.org), the SIMPLE case mappings:
field 12 (Simple_Uppercase_Mapping) and field 13 (Simple_Lowercase_Mapping). UNOFFICIAL for Windows: no Microsoft page gives LCMapStringW's case table outside the Windows 8 Upper Case Mapping Table
rows kept in fle_locale.c (the range D of decision 0087, which this table does NOT replace). Decision 0087 recorded UCD 16.0.0 and SHA-256 ff58e582...edb48f for the same file.
usage: gen_crash1_case.py UnicodeData-16.0.0.txt OUT.inc [EXPECT.tsv]
The table is a list of runs {first, count, stride, up, lo}: for k in 0..count-1, code point first + k*stride has upper case (cp + up) and lower case (cp + lo) (0 = no mapping).
The check: every code point of the UCD with a mapping is covered exactly, no run maps across the BMP boundary, no run touches D (U+0000..U+00FF and the 28 units above it are answered by fle_locale.c's table first).
"""
import hashlib, sys

src, out = sys.argv[1], sys.argv[2]
raw = open(src, 'rb').read()
sha = hashlib.sha256(raw).hexdigest()
up, lo = {}, {}
for line in raw.decode('utf-8').splitlines():
    f = line.split(';')
    if len(f) < 15: continue
    cp = int(f[0], 16)
    if f[12]: up[cp] = int(f[12], 16)
    if f[13]: lo[cp] = int(f[13], 16)
cps = sorted(set(up) | set(lo))
for cp in cps:
    for m in (up.get(cp), lo.get(cp)):
        if m is not None and (m < 0x10000) != (cp < 0x10000):
            raise SystemExit(f'U+{cp:04X} maps across the BMP boundary')
# greedy runs of equal (up delta, lo delta) at a fixed stride (1 or 2)
runs = []
used = set()
i = 0
def delta(cp): return (up.get(cp, cp) - cp, lo.get(cp, cp) - cp)
while i < len(cps):
    cp = cps[i]
    d = delta(cp)
    best = (1, 1)
    for stride in (1, 2):
        n = 1
        while (cp + n * stride) in set(cps[i:i + 4 * n + 8]) and delta(cp + n * stride) == d and cp + n * stride not in used:
            n += 1
        if n > best[0]: best = (n, stride)
    n, stride = best
    runs.append((cp, n, stride, d[0], d[1]))
    for k in range(n): used.add(cp + k * stride)
    # advance to the first code point not used
    while i < len(cps) and cps[i] in used: i += 1
runs.sort()
# verify
got_up, got_lo = {}, {}
for first, n, stride, du, dl in runs:
    for k in range(n):
        cp = first + k * stride
        if du: got_up[cp] = cp + du
        if dl: got_lo[cp] = cp + dl
assert {k: v for k, v in up.items() if v != k} == got_up, 'upper mismatch'
assert {k: v for k, v in lo.items() if v != k} == got_lo, 'lower mismatch'
with open(out, 'w') as o:
    o.write('/* GENERATED by lift/runtime/test/gen_crash1_case.py (decision 0209). Do not edit.\n')
    o.write(f' * Simple case mappings (UnicodeData.txt fields 12 and 13) of the Unicode Character Database 16.0.0 (unicode.org; UNOFFICIAL for Windows: the case table of LCMapStringW is not on the Microsoft pages).\n')
    o.write(f' * UnicodeData-16.0.0.txt SHA-256 {sha}. {len(cps)} code points with a mapping ({len(up)} upper, {len(lo)} lower) in {len(runs)} runs {{first, count, stride, upper delta, lower delta}}. */\n')
    for first, n, stride, du, dl in runs:
        o.write(f'{{0x{first:05X}, {n}, {stride}, {du}, {dl}}},\n')
if len(sys.argv) > 3:
    with open(sys.argv[3], 'w') as e:
        e.write(f'# GENERATED by gen_crash1_case.py (decision 0209) from UnicodeData-16.0.0.txt SHA-256 {sha}: code point, simple upper, simple lower (hex; = the code point when none). Only code points with a mapping.\n')
        for cp in cps: e.write(f'{cp:05X}\t{up.get(cp, cp):05X}\t{lo.get(cp, cp):05X}\n')
print(len(cps), len(up), len(lo), len(runs), sha)
