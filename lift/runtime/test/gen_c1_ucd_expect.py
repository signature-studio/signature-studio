#!/usr/bin/env python3
"""Derives C1_UPPER and C1_LOWER from the Unicode Character Database 16.0.0 for the units of the Wine data file
(lift/runtime/test/c1_wine_10_0_enus.txt) and checks that Wine's UPPER and LOWER bits equal them (decision 0087). The UCD is used
only to check Wine's values; it is not the source of the values. Writes lift/runtime/test/c1_ucd16_upper_lower.txt.

usage: gen_c1_ucd_expect.py UnicodeData-16.0.0.txt DerivedCoreProperties-16.0.0.txt C1_WINE.txt OUT.txt

The two UCD files are the unicode.org files for version 16.0.0 (gitignored work files); their SHA-256 values are checked first.
Rule: C1_UPPER = (General_Category == Lu), C1_LOWER = (derived property Lowercase). Exit 1 on any difference from Wine's bits
(and nothing is written). OUT.txt must not exist (it is never overwritten). Only the Python standard library is used.
Reproduce:  python3 lift/runtime/test/gen_c1_ucd_expect.py lift/out-ctype/ref/UnicodeData-16.0.0.txt \\
              lift/out-ctype/ref/DerivedCoreProperties-16.0.0.txt lift/runtime/test/c1_wine_10_0_enus.txt OUT.txt
"""
import hashlib
import sys

UNICODEDATA_SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"
DERIVED_SHA256 = "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd"


def read_checked(path: str, sha: str) -> str:
    raw = open(path, "rb").read()
    if hashlib.sha256(raw).hexdigest() != sha:
        raise SystemExit(path + ": SHA-256 differs from the one in decision 0087")
    return raw.decode("utf-8")


def general_category(text: str) -> dict:
    gc = {}
    for l in text.split("\n"):
        f = l.split(";")
        if len(f) > 2 and not f[1].endswith(", First>") and not f[1].endswith(", Last>"):
            gc[int(f[0], 16)] = f[2]
    return gc


def derived(text: str, prop: str) -> set:
    s = set()
    for l in text.split("\n"):
        l = l.split("#")[0].strip()
        if not l:
            continue
        r, p = [x.strip() for x in l.split(";")][:2]
        if p != prop:
            continue
        a, _, b = r.partition("..")
        s.update(range(int(a, 16), int(b or a, 16) + 1))
    return s


def main() -> int:
    if len(sys.argv) != 5:
        print(__doc__, file=sys.stderr)
        return 64
    ud, dcp, wine, out = sys.argv[1:]
    gc = general_category(read_checked(ud, UNICODEDATA_SHA256))
    lower = derived(read_checked(dcp, DERIVED_SHA256), "Lowercase")
    rows = []
    for l in open(wine).read().split("\n"):
        if l and not l.startswith("#"):
            u, v = l.split()
            rows.append((int(u, 16), int(v, 16)))
    if len(rows) != 283:
        raise SystemExit("the Wine data file does not have 283 rows")
    bad = []
    lines = [
        "# GENERATED by lift/runtime/test/gen_c1_ucd_expect.py (decision 0087). Do not edit.",
        "# C1_UPPER and C1_LOWER derived from the UCD 16.0.0 (unicode.org; UNOFFICIAL, not Microsoft's rule): UPPER = General_Category",
        "# Lu, LOWER = derived property Lowercase. UnicodeData-16.0.0.txt SHA-256 " + UNICODEDATA_SHA256 + ",",
        "# DerivedCoreProperties-16.0.0.txt SHA-256 " + DERIVED_SHA256 + ". The generator checked that Wine's UPPER (0x1) and",
        "# LOWER (0x2) bits equal these for all 283 units of c1_wine_10_0_enus.txt (zero differences). One row per unit: unit, UPPER, LOWER.",
    ]
    for u, v in rows:
        up, lo = int(gc.get(u) == "Lu"), int(u in lower)
        if (v & 1) != up or ((v >> 1) & 1) != lo:
            bad.append("U+%04X wine %#06x ucd upper %d lower %d (gc %s)" % (u, v, up, lo, gc.get(u)))
        lines.append("0x%04X %d %d" % (u, up, lo))
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    with open(out, "x") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
