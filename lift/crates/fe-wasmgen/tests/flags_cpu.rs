//! Decision 0270 (mt3w), flag recipes against the CPU. (1) A shift by cl (`shl/shr/sar r8b|r16|r32|r64, cl`) whose flags are read: a count of 0 (after the mask) leaves every flag as it was, CF/ZF/SF/PF follow the shift otherwise (OF only for a count of 1: not modelled).
//! The same machine code is run on the host CPU (a page from mmap) and as a lifted function under node, and the results are compared:
//!   - function: `rdx` selects the instruction that defines the flags before the shift (0 `cmp rdi,rsi`, 1 `test`, 2 `add`, 3 `sub`: four definitions that merge), then `<op> r8<w>, cl`, then a reader: V the value (`mov rax,r8`), 1 `setb/setz/sets/setp`,
//!     2 a `jbe / js / jp` chain, 3 `cmovz / cmovs / cmovp` + `adc` (the code is generated by `gen_flags_cpu.py` into `flags_cpu_code.rs`);
//!   - input flags: 4 definitions x 10 operand pairs = 40 flag states; counts 0 1 2 7 8 9 15 16 17 31 32 33 63 64; 5 values; 3 operations x 4 widths x 4 readers = 48 functions. (An 8 or 16 bit operand with a masked count above its width has
//!     undefined flags: the lifted code stops there, as the C path's `fle_bad_count` does, so those counts are not run.)
//! (2) `bsf` / `bsr` (below) ZF = (source == 0), the destination untouched for a zero source. Also: a reader of OF after a shift by cl stays on the C path. Skipped (and passing) when node is missing; Linux x86-64 only (the host run).
#![cfg(all(target_arch = "x86_64", target_os = "linux"))]

use fe_wasmgen::{compile, Config};
use std::collections::HashMap;
use std::process::Command;

mod flags_cpu_code;

fn w16(b: &mut [u8], o: usize, v: u16) {
    b[o..o + 2].copy_from_slice(&v.to_le_bytes());
}
fn w32(b: &mut [u8], o: usize, v: u32) {
    b[o..o + 4].copy_from_slice(&v.to_le_bytes());
}
fn w64(b: &mut [u8], o: usize, v: u64) {
    b[o..o + 8].copy_from_slice(&v.to_le_bytes());
}

/// a PE with functions at 0x401000 + `at` (each `(offset from 0x401000, code)`), listed in .pdata
fn pe(funcs: &[(u32, &[u8])]) -> Vec<u8> {
    let mut b = vec![0u8; 0xc00];
    let (lf, opt) = (0x80usize, 0x80 + 24);
    let sec = opt + 240;
    w16(&mut b, 0, 0x5a4d);
    w32(&mut b, 0x3c, lf as u32);
    w32(&mut b, lf, 0x4550);
    let f = lf + 4;
    w16(&mut b, f, 0x8664);
    w16(&mut b, f + 2, 2);
    w16(&mut b, f + 16, 240);
    w16(&mut b, f + 18, 0x2022);
    w16(&mut b, opt, 0x20b);
    w32(&mut b, opt + 16, 0x1000);
    w64(&mut b, opt + 24, 0x400000);
    w32(&mut b, opt + 32, 0x1000);
    w32(&mut b, opt + 36, 0x200);
    w32(&mut b, opt + 56, 0x3000);
    w32(&mut b, opt + 60, 0x400);
    w16(&mut b, opt + 68, 3);
    w32(&mut b, opt + 108, 16);
    w32(&mut b, opt + 112 + 3 * 8, 0x2000);
    w32(&mut b, opt + 112 + 3 * 8 + 4, 12 * funcs.len() as u32);
    let mut section = |i: usize, name: &[u8], vs: u32, rva: u32, rs: u32, rp: u32, ch: u32| {
        let s = sec + 40 * i;
        b[s..s + name.len()].copy_from_slice(name);
        w32(&mut b, s + 8, vs);
        w32(&mut b, s + 12, rva);
        w32(&mut b, s + 16, rs);
        w32(&mut b, s + 20, rp);
        w32(&mut b, s + 36, ch);
    };
    section(0, b".text", 0x400, 0x1000, 0x400, 0x400, 0x60000020);
    section(1, b".pdata", 0x200, 0x2000, 0x400, 0x800, 0x40000040);
    for (n, (off, code)) in funcs.iter().enumerate() {
        let at = 0x400 + *off as usize;
        b[at..at + code.len()].copy_from_slice(code);
        let p = 0x800 + 12 * n;
        w32(&mut b, p, 0x1000 + off);
        w32(&mut b, p + 4, 0x1000 + off + code.len() as u32);
        w32(&mut b, p + 8, 0x2100);
    }
    b[0x900..0x904].copy_from_slice(&[1, 0, 0, 0]);
    b
}

fn conf() -> Config {
    let mut ci: HashMap<String, String> = HashMap::new();
    ci.insert("dummy".into(), "fle_imp_dummy".into());
    Config {
        hybrid_r: Some(0x2000),
        tls_ctx: Some(0x2000),
        hybrid_x: Some(0x2200),
        hybrid_mx: Some((0x3000, 0x3100)),
        c_imports: Some(ci),
        mem_import: Some(("c".into(), "memory".into())),
        teb: Some(0x1000),
        ..Config::default()
    }
}

const JS: &str = r#"
const fs = require('fs');
const [wasmF, casesF, outF] = process.argv.slice(2);
const mem = new WebAssembly.Memory({ initial: 16, maximum: 32768, shared: true });
const dv = new DataView(mem.buffer);
const m = new WebAssembly.Module(fs.readFileSync(wasmF));
const R = 0x2000;
const imports = { c: { memory: mem, __tls_base: new WebAssembly.Global({ value: 'i32', mutable: true }, 0) } };
for (const i of WebAssembly.Module.imports(m)) {
  if (i.kind !== 'function') continue;
  imports[i.module] = imports[i.module] || {};
  imports[i.module][i.name] = () => { throw new Error('unexpected call of ' + i.module + '.' + i.name); };
}
const inst = new WebAssembly.Instance(m, imports);
const cases = JSON.parse(fs.readFileSync(casesF, 'utf8'));
const out = [];
for (const c of cases) {
  for (let r = 0; r < 16; r++) dv.setBigUint64(R + 8 * r, BigInt(c.regs && c.regs[r] !== undefined ? c.regs[r] : '0'), true);
  for (const [a, v] of (c.mem || [])) dv.setBigUint64(a, BigInt(v), true);
  inst.exports[c.fn]();
  const regs = []; for (let r = 0; r < 16; r++) regs.push(dv.getBigUint64(R + 8 * r, true).toString());
  out.push({ regs, mem: (c.read || []).map((a) => dv.getBigUint64(a, true).toString()) });
}
fs.writeFileSync(outF, JSON.stringify({ out }));
"#;

fn have(tool: &str) -> bool {
    Command::new(tool).arg("--version").output().is_ok()
}

fn run_node(wasm: &[u8], cases: &str, tag: &str) -> Vec<Vec<u64>> {
    let dir = std::env::temp_dir().join(format!("fe-wasmgen-flagscpu-{}-{}", std::process::id(), tag));
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("t.wasm"), wasm).unwrap();
    std::fs::write(dir.join("cases.json"), cases).unwrap();
    std::fs::write(dir.join("run.cjs"), JS).unwrap();
    let o = Command::new("node").arg(dir.join("run.cjs")).arg(dir.join("t.wasm")).arg(dir.join("cases.json")).arg(dir.join("out.json")).output().unwrap();
    assert!(o.status.success(), "node: {}", String::from_utf8_lossy(&o.stderr));
    let txt = std::fs::read_to_string(dir.join("out.json")).unwrap();
    let _ = std::fs::remove_dir_all(&dir);
    // each case: its 16 registers, then its `read` words
    txt.split("{\"regs\":[").skip(1).map(|c| {
        let re = c.find(']').unwrap();
        let mut v: Vec<u64> = c[..re].split(',').map(|x| x.trim_matches('"').parse().unwrap()).collect();
        let rest = &c[re..];
        let ms = &rest[rest.find("\"mem\":[").unwrap() + 7..];
        let me = ms.find(']').unwrap();
        v.extend(ms[..me].split(',').filter(|x| !x.is_empty()).map(|x| x.trim_matches('"').parse::<u64>().unwrap()));
        v
    }).collect()
}

fn lowered(funcs: &[(u32, &[u8])]) -> (fe_wasmgen::Compiled, Vec<u64>) {
    let keys: Vec<u64> = funcs.iter().map(|(o, _)| 0x401000 + *o as u64).collect();
    let comp = compile(&pe(funcs), &keys, &[], &conf()).unwrap_or_else(|e| panic!("compile: {e}"));
    (comp, keys)
}


extern "C" {
    fn mmap(addr: *mut u8, len: usize, prot: i32, flags: i32, fd: i32, off: i64) -> *mut u8;
}

/// the machine code as a function of the host: (rdi, rsi, rdx, rcx, r8) -> rax
fn host_fn(code: &[u8]) -> extern "C" fn(u64, u64, u64, u64, u64) -> u64 {
    unsafe {
        let p = mmap(std::ptr::null_mut(), 4096, 7, 0x22, -1, 0);
        assert!(p as isize != -1, "mmap");
        std::ptr::copy_nonoverlapping(code.as_ptr(), p, code.len());
        std::mem::transmute(p)
    }
}

fn case(a: u64, b: u64, sel: u64, cnt: u64, val: u64) -> String {
    format!("{{\"fn\":\"f_401000\",\"regs\":{{\"1\":\"{cnt}\",\"2\":\"{sel}\",\"4\":\"524288\",\"6\":\"{b}\",\"7\":\"{a}\",\"8\":\"{val}\"}},\"read\":[]}}")
}

const PAIRS: [(u64, u64); 10] = [
    (0, 0),
    (1, 0),
    (0, 1),
    (0x7fff_ffff_ffff_ffff, 1),
    (0x8000_0000_0000_0000, 1),
    (u64::MAX, 1),
    (5, 5),
    (0x0f, 0xf0),
    (0x80, 0x80),
    (1, u64::MAX),
];
const COUNTS: [u64; 14] = [0, 1, 2, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64];
const VALUES: [u64; 5] = [0x0123_4567_89ab_cdef, u64::MAX, 0x8000_0000_0000_0001, 0x80, 0];

#[test]
fn a_shift_by_cl_gives_the_flags_and_the_value_of_the_cpu() {
    if !have("node") {
        eprintln!("SKIPPED node: not installed");
        return;
    }
    let mut total = 0usize;
    let mut bad: Vec<String> = Vec::new();
    for (op, w, rd, code) in flags_cpu_code::SHIFT {
        let comp = compile(&pe(&[(0, code)]), &[0x401000], &[], &conf()).unwrap_or_else(|e| panic!("compile: {e}"));
        assert!(comp.fidx.contains_key(&0x401000), "{op} {w} {rd}: was not lowered: {:?}", comp.report.rows.iter().find(|r| r.va == 0x401000).map(|r| r.status.clone()));
        let host = host_fn(code);
        let mask = if *w == 64 { 63 } else { 31 };
        let mut cases: Vec<String> = Vec::new();
        let mut want: Vec<u64> = Vec::new();
        for &cnt in &COUNTS {
            if (cnt & mask) > *w as u64 {
                continue;
            }
            for sel in 0..4u64 {
                for &(a, b) in &PAIRS {
                    for &val in &VALUES {
                        cases.push(case(a, b, sel, cnt, val));
                        want.push(host(a, b, sel, cnt, val));
                    }
                }
            }
        }
        let got = run_node(&comp.wasm, &format!("[{}]", cases.join(",")), &format!("{op}{w}{rd}"));
        assert_eq!(got.len(), want.len());
        let mut k = 0usize;
        for &cnt in &COUNTS {
            if (cnt & mask) > *w as u64 {
                continue;
            }
            for sel in 0..4u64 {
                for &(a, b) in &PAIRS {
                    for &val in &VALUES {
                        if got[k][0] != want[k] && bad.len() < 12 {
                            bad.push(format!("{op} {w} reader {rd}: count {cnt} sel {sel} a {a:#x} b {b:#x} val {val:#x}: lifted {:#x}, cpu {:#x}", got[k][0], want[k]));
                        }
                        k += 1;
                    }
                }
            }
        }
        total += k;
    }
    assert!(bad.is_empty(), "differences (of {total} runs):\n{}", bad.join("\n"));
    eprintln!("shift by cl: {total} runs equal to the CPU");
}

#[test]
fn a_reader_of_of_after_a_shift_by_cl_stays_on_the_c_path() {
    // shr r8, cl; seto al; ret
    let code: Vec<u8> = vec![0x49, 0xd3, 0xe8, 0x0f, 0x90, 0xc0, 0xc3];
    let comp = compile(&pe(&[(0, &code)]), &[0x401000], &[], &conf()).unwrap();
    assert!(!comp.fidx.contains_key(&0x401000));
    let st = comp.report.rows.iter().find(|r| r.va == 0x401000).map(|r| r.status.clone()).unwrap_or_default();
    assert!(st.contains("without recipe") && st.contains("flag 0x20"), "{st}");
}

const SOURCES: [u64; 12] = [0, 1, 2, 0x80, 0x8000, 0x7fff_ffff, 0x8000_0000, 0x1_0000_0000, 0xffff_0000, 0x8000_0000_0000_0000, u64::MAX, 0x0123_4567_89ab_cdef];
const OLD: [u64; 2] = [0x55, 0x1122_3344_5566_7788];

#[test]
fn bsf_and_bsr_give_the_zf_and_the_destination_of_the_cpu() {
    if !have("node") {
        eprintln!("SKIPPED node: not installed");
        return;
    }
    let (mut total, mut bad) = (0usize, Vec::<String>::new());
    for (op, w, rd, code) in flags_cpu_code::BSCAN {
        let comp = compile(&pe(&[(0, code)]), &[0x401000], &[], &conf()).unwrap_or_else(|e| panic!("compile: {e}"));
        assert!(comp.fidx.contains_key(&0x401000), "{op} {w} {rd}: was not lowered: {:?}", comp.report.rows.iter().find(|r| r.va == 0x401000).map(|r| r.status.clone()));
        let host = host_fn(code);
        let mut cases: Vec<String> = Vec::new();
        let mut args: Vec<(u64, u64, u64)> = Vec::new();
        for skip in [1u64, 0] {
            for &s in &SOURCES {
                for &old in &OLD {
                    // rax = old destination (index 0), rcx = 1 (the bit scan runs) or 0 (the merge variant skips it), rdx = the source
                    cases.push(format!("{{\"fn\":\"f_401000\",\"regs\":{{\"0\":\"{old}\",\"1\":\"{skip}\",\"2\":\"{s}\",\"4\":\"524288\"}},\"read\":[]}}"));
                    args.push((old, skip, s));
                }
            }
        }
        let got = run_node(&comp.wasm, &format!("[{}]", cases.join(",")), &format!("{op}{w}{rd}"));
        for (k, &(old, skip, s)) in args.iter().enumerate() {
            // the host function takes (rdi, rsi, rdx, rcx, r8) -> rax: the old destination comes in rax, which the C ABI does not pass; the test code is called through a stub that loads it
            let want = host_with_rax(code, old, skip, s);
            if got[k][0] != want && bad.len() < 12 {
                bad.push(format!("{op} {w} reader {rd}: old {old:#x} rcx {skip} source {s:#x}: lifted {:#x}, cpu {:#x}", got[k][0], want));
            }
            let _ = &host;
            total += 1;
        }
    }
    assert!(bad.is_empty(), "differences (of {total} runs):\n{}", bad.join("\n"));
    eprintln!("bsf/bsr: {total} runs equal to the CPU");
}

/// runs `code` on the host with rax = `rax`, rcx = `rcx`, rdx = `rdx` (a small stub in front of it loads rax from rdi, rcx from rsi, rdx from rdx: `mov rax,rdi; mov rcx,rsi; <code>`)
fn host_with_rax(code: &[u8], rax: u64, rcx: u64, rdx: u64) -> u64 {
    let mut stub: Vec<u8> = vec![0x48, 0x89, 0xf8, 0x48, 0x89, 0xf1];
    stub.extend_from_slice(code);
    let f = host_fn(&stub);
    f(rax, rcx, rdx, 0, 0)
}
