#!/usr/bin/env python3
# mt3w 0270: assembles the test functions of tests/flags_cpu.rs (GNU as, Intel syntax) and prints them as a Rust table.
# Each function: rdi = A, rsi = B, rdx = selector of the instruction that defines the flags before the shift (0 cmp, 1 test, 2 add, 3 sub), rcx = count, r8 = the value shifted.
# The flags after `<op> r8<w>, cl` are read by one of: V (the value: mov rax,r8), 1 (setcc pack of CF ZF SF PF), 2 (jcc chain), 3 (cmov + adc).
import subprocess, os, sys, tempfile
WID = {8: 'r8b', 16: 'r8w', 32: 'r8d', 64: 'r8'}
PRE = """
  cmp edx, 1
  je 1f
  cmp edx, 2
  je 2f
  cmp edx, 3
  je 3f
  cmp rdi, rsi
  jmp 9f
1:
  test rdi, rsi
  jmp 9f
2:
  add rdi, rsi
  jmp 9f
3:
  sub rdi, rsi
9:
"""
READ = {
 'V': "  mov rax, r8\n  ret\n",
 '1': """  setb al
  setz r9b
  sets r10b
  setp cl
  movzx eax, al
  movzx r9d, r9b
  movzx r10d, r10b
  movzx ecx, cl
  lea eax, [rax + r9*2]
  lea eax, [rax + r10*4]
  lea eax, [rax + rcx*8]
  ret
""",
 '2': """  jbe 1f
  js 2f
  jp 3f
  mov eax, 0
  ret
1:
  mov eax, 1
  ret
2:
  mov eax, 2
  ret
3:
  mov eax, 3
  ret
""",
 '3': """  mov eax, 0
  mov edx, 0
  mov ecx, 0
  mov r9d, 1
  mov r10d, 2
  mov r11d, 4
  cmovz eax, r9d
  cmovs edx, r10d
  cmovp ecx, r11d
  lea eax, [rax + rdx]
  lea eax, [rax + rcx]
  adc eax, eax
  ret
""",
}
def asm(text):
    d = tempfile.mkdtemp(dir=os.environ['TMPDIR'])
    s, o, b = d + '/a.s', d + '/a.o', d + '/a.bin'
    open(s, 'w').write(".intel_syntax noprefix\n.text\n" + text)
    subprocess.check_call(['as', '--64', '-o', o, s])
    subprocess.check_call(['objcopy', '-O', 'binary', '-j', '.text', o, b])
    r = open(b, 'rb').read()
    for f in (s, o, b): os.remove(f)
    os.rmdir(d)
    return r
out = []
for op in ('shl', 'shr', 'sar'):
    for w in (8, 16, 32, 64):
        for rd in ('V', '1', '2', '3'):
            code = asm(PRE + f"  {op} {WID[w]}, cl\n" + READ[rd])
            out.append((op, w, rd, code))
# bsf / bsr rax|eax|ax, rdx|edx|dx (rax = the old destination, rdx = the source, rcx = 0 makes the merge variant skip it); readers: V the register (ret), Z ZF as 0/1, M ZF after a test that the bit scan may skip
REG = {16: ('ax', 'dx'), 32: ('eax', 'edx'), 64: ('rax', 'rdx')}
bscan = []
for op in ('bsf', 'bsr'):
    for w in (16, 32, 64):
        d, s_ = REG[w]
        tails = {
          'V': f"  {op} {d}, {s_}\n  ret\n",
          'Z': f"  {op} {d}, {s_}\n  setz al\n  movzx eax, al\n  ret\n",
          'M': f"  test rcx, rcx\n  jz 1f\n  {op} {d}, {s_}\n1:\n  setz al\n  movzx eax, al\n  ret\n",
        }
        for rd, text in tails.items():
            bscan.append((op, w, rd, asm(text)))
def table(name, rows):
    print(f"pub const {name}: &[(&str, u32, char, &[u8])] = &[")
    for op, w, rd, code in rows:
        print(f'    ("{op}", {w}, \'{rd}\', &[{", ".join("0x%02x" % x for x in code)}]),')
    print("];")
print("// generated by tools/gen_flags_cpu.py (GNU as, Intel syntax); do not edit")
table("SHIFT", out)
table("BSCAN", bscan)
