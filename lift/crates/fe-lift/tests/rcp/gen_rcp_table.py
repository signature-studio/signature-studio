#!/usr/bin/env python3
"""Generates lift/runtime/fle_rcp_table.h (decision 0047) from the output of tests/rcp/host_dump.c.

usage: gen_rcp_table.py HOST_DUMP.txt OUT.h

HOST_DUMP.txt: 4096 lines, the 12 result-mantissa bits of the host RCPPS for each index (top 12 bits of the
source mantissa). The header is plain C data; the run time has no dependence on the host CPU.
Reproduce:  clang -O1 -o host_dump tests/rcp/host_dump.c && ./host_dump > dump.txt
            python3 tests/rcp/gen_rcp_table.py dump.txt runtime/fle_rcp_table.h
"""
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 64
    vals = [int(l) for l in open(sys.argv[1]).read().split()]
    if len(vals) != 4096 or any(not 0 <= v < 4096 for v in vals):
        print("host dump must hold 4096 values in 0..4095", file=sys.stderr)
        return 1
    out = []
    out.append("/* GENERATED by tests/rcp/gen_rcp_table.py from the output of tests/rcp/host_dump.c (decision 0047).\n")
    out.append(" * Do not edit. fle_rcp_tab[i]: the 12 mantissa bits of RCPPS for a source whose mantissa top 12 bits are i\n")
    out.append(" * (result mantissa bits [22:11]; bits [10:0] are 0). Measured on an AMD Ryzen 9 9950X (Zen 5); an Intel\n")
    out.append(" * CPU is unverified. Source: the host RCPPS only; the SDM gives no table. */\n")
    out.append("#ifndef FLE_RCP_TABLE_H\n#define FLE_RCP_TABLE_H\n\n#include <stdint.h>\n\n")
    out.append("static const uint16_t fle_rcp_tab[4096] = {\n")
    for r in range(0, 4096, 16):
        out.append("    " + ", ".join(str(v) for v in vals[r : r + 16]) + ",\n")
    out.append("};\n\n#endif\n")
    with open(sys.argv[2], "x") as f:
        f.write("".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
