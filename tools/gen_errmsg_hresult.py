#!/usr/bin/python3
"""Decision 0129 (S-errmsg-hresult-learn-text): writes runtime/fle_errmsg_hresult.h from the saved Learn page 'COM Error Codes (Generic)' (https://learn.microsoft.com/en-us/windows/win32/com/com-error-codes-1).
The page lists, for each HRESULT, three lines: the name, the value (0x8004xxxx) and the text. Only the HRESULTs in WANTED (the ones the guest has asked FormatMessageW about) are written: the text is
the page's text, without any character that the page does not hold (no CR LF, no final period that is not in the page). usage: gen_errmsg_hresult.py LEARN_TXT OUT_H"""
import re, sys
WANTED = ["REGDB_E_CLASSNOTREG"]
lines = [l.strip() for l in open(sys.argv[1], encoding="utf-8") if l.strip()]
rows = []
for i, l in enumerate(lines):
    if l in WANTED and i + 2 < len(lines) and re.fullmatch(r"0x[0-9A-Fa-f]{8}", lines[i + 1]):
        rows.append((int(lines[i + 1], 16), l, lines[i + 2]))
assert len(rows) == len(WANTED), (len(rows), WANTED)
with open(sys.argv[2], "w", encoding="utf-8") as o:
    o.write("/* generated by tools/gen_errmsg_hresult.py (decision 0129, S-errmsg-hresult-learn-text) from Microsoft Learn 'COM Error Codes (Generic)': the HRESULTs that the guest has asked FormatMessageW(FROM_SYSTEM) about and their texts, exactly as the page holds them. A reading: that FormatMessage returns these texts on a real Windows is NOT measured. */\n")
    o.write("static const struct { uint32_t code; const char *name; const char *text; } fle_errmsg_hresult[] = {\n")
    for c, n, t in rows:
        o.write('    { 0x%08Xu, "%s", "%s" },\n' % (c, n, t.replace("\\", "\\\\").replace('"', '\\"')))
    o.write("};\n")
